/**
 * Normalizes legacy Vietnamese chemical terms into GDPT 2018 IUPAC terminology
 */
export function normalizeChemicalNomenclature(text: string): { text: string; changed: boolean } {
  if (!text) return { text: '', changed: false };
  let current = text;
  let changed = false;

  for (const rule of IUPAC_REPLACEMENTS) {
    if (rule.pattern.test(current)) {
      current = current.replace(rule.pattern, rule.replacement);
      changed = true;
    }
  }
  return { text: current, changed };
}

/**
 * Automatically detects KHTN domain, grade, and difficulty from question text
 */
export function detectDomainAndGrade(
  text: string,
  fallbackDomain: SubjectDomain = 'hoa-hoc',
  fallbackGrade: Grade = 8
): {
  domain: SubjectDomain;
  grade: Grade;
  difficulty: 'Nhận biết' | 'Thông hiểu' | 'Vận dụng';
} {
  const lower = text.toLowerCase();

  let domain: SubjectDomain = fallbackDomain;
  if (
    /(điện trở|cường độ dòng điện|hiệu điện thế|ohm|khúc xạ|lăng kính|tia sáng|áp suất|archimedes|lực đẩy|tốc độ|quãng đường|công suất|ampe|vôn kế|nhiệt lượng|động năng|thế năng)/i.test(
      lower
    )
  ) {
    domain = 'vat-li';
  } else if (
    /(tế bào|lục lạp|ti thể|nhân tế bào|quang hợp|hô hấp|dna|rna|nucleotide|adenine|thymine|guanine|cytosine|di truyền|mendel|nhiễm sắc thể|gene|sinh vật|kính hiển vi)/i.test(
      lower
    )
  ) {
    domain = 'sinh-hoc';
  } else if (
    /(nguyên tử|phân tử|proton|neutron|electron|acid|base|ph|oxide|muối|phản ứng|hóa học|bảo toàn khối lượng|mol|nồng độ|sodium|oxygen|hydrogen|carbon|chlorine|copper|iron|hcl|naoh|h2so4)/i.test(
      lower
    )
  ) {
    domain = 'hoa-hoc';
  }

  let grade: Grade = fallbackGrade;
  if (/(tế bào|kính hiển vi|các thể của chất|lực tiếp xúc|khối lượng riêng|lớp 6)/i.test(lower)) {
    grade = 6;
  } else if (/(rutherford|bohr|bảng tuần hoàn|tốc độ|âm thanh|quang hợp|lớp 7)/i.test(lower)) {
    grade = 7;
  } else if (/(acid|base|thang ph|oxide|bảo toàn khối lượng|áp suất|archimedes|lớp 8)/i.test(lower)) {
    grade = 8;
  } else if (/(định luật ohm|khúc xạ|snell|dna|rna|nucleotide|methane|ethylene|ethanol|acetic|glucose|lớp 9)/i.test(lower)) {
    grade = 9;
  }

  let difficulty: 'Nhận biết' | 'Thông hiểu' | 'Vận dụng' = 'Thông hiểu';
  if (
    (/(tính|bao nhiêu|xác định giá trị|khối lượng thu được|nồng độ|cường độ dòng điện bằng|chiều dài phân tử|trình bày các bước|viết phương trình)/i.test(
      lower
    ) &&
      /\d/.test(lower)) ||
    /(tự luận|giải thích hiện tượng và viết phương trình)/i.test(lower)
  ) {
    difficulty = 'Vận dụng';
  } else if (/(là gì|kí hiệu|công thức nào|đơn vị của|bào quan nào|môi trường nào)/i.test(lower)) {
    difficulty = 'Nhận biết';
  }

  return { domain, grade, difficulty };
}

/**
 * Infers the most likely correct option index (0..3) when no explicit answer key is marked in the Word file
 */
export function inferCorrectOptionFromKnowledge(question: string, options: string[]): number | null {
  const qLower = question.toLowerCase();

  for (let i = 0; i < options.length; i++) {
    const optLower = options[i].toLowerCase();

    // Chemistry rules
    if (qLower.includes('hạt nhân') && (optLower.includes('proton và neutron') || optLower.includes('proton, neutron'))) {
      return i;
    }
    if (qLower.includes('mang điện tích âm') && optLower.includes('electron')) {
      return i;
    }
    if (qLower.includes('mang điện tích dương') && optLower.includes('proton')) {
      return i;
    }
    if (qLower.includes('không mang điện') && optLower.includes('neutron')) {
      return i;
    }
    if (qLower.includes('môi trường acid') && (optLower.includes('ph < 7') || optLower.includes('hóa đỏ'))) {
      return i;
    }
    if (qLower.includes('môi trường base') && (optLower.includes('ph > 7') || optLower.includes('hóa xanh') || optLower.includes('màu hồng'))) {
      return i;
    }
    if (qLower.includes('bảo toàn khối lượng') && optLower.includes('bằng tổng khối lượng')) {
      return i;
    }
    if (qLower.includes('h₂ +') && qLower.includes('o₂') && (optLower.includes('2, 1, 2') || optLower.includes('2h₂ + o₂'))) {
      return i;
    }

    // Physics rules
    if (qLower.includes('định luật ohm') && (optLower.includes('i = u / r') || optLower.includes('i = u/r'))) {
      return i;
    }
    if (qLower.includes('công thức tính áp suất') && (optLower.includes('p = f / s') || optLower.includes('p = f/s'))) {
      return i;
    }
    if (qLower.includes('archimedes') && (optLower.includes('d × v') || optLower.includes('d.v') || optLower.includes('d * v'))) {
      return i;
    }
    if (qLower.includes('khúc xạ') && (optLower.includes('sin') || optLower.includes('r = 0'))) {
      return i;
    }

    // Biology rules
    if (qLower.includes('quang hợp') && optLower.includes('lục lạp')) {
      return i;
    }
    if (qLower.includes('hô hấp tế bào') && optLower.includes('ti thể')) {
      return i;
    }
    if (qLower.includes('thành tế bào thực vật') && optLower.includes('cellulose')) {
      return i;
    }
    if (qLower.includes('guanine') && qLower.includes('cytosine') && optLower.includes('3 liên kết')) {
      return i;
    }
    if (qLower.includes('adenine') && qLower.includes('thymine') && optLower.includes('2 liên kết')) {
      return i;
    }
  }

  return null;
}

/**
 * Generates structured step-by-step solution instructions (Bước 1, Bước 2, Bước 3, Bước 4)
 * for any KHTN question (both multiple-choice and essay).
 */
export function generateStepByStepSolution(params: {
  question: string;
  options: string[];
  correctAnswer?: number;
  questionType?: QuestionType;
  domain: SubjectDomain;
  grade: Grade;
  existingExplanation?: string;
}): string[] {
  const {
    question,
    options,
    correctAnswer = 0,
    questionType = 'single_choice',
    existingExplanation,
  } = params;

  const isEssay = questionType === 'essay' || options.length === 0;
  const letter = String.fromCharCode(
    65 + (correctAnswer >= 0 && correctAnswer < options.length ? correctAnswer : 0)
  );
  const correctText = !isEssay ? options[correctAnswer] || options[0] || '' : '';
  const qLower = question.toLowerCase();

  // If existing explanation already contains explicit "Bước 1", "Bước 2", extract them directly (preserving Dữ kiện and [EQ] lines)
  if (existingExplanation && /Bước\s*1\s*[:(-]/i.test(existingExplanation)) {
    const rawParts = existingExplanation
      .split(/\n(?=(?:Dữ\s*kiện\s*:|[-•+]\s*Bước\s*\d+|Bước\s*\d+\s*[:(-]))/i)
      .map((s) => s.replace(/^[-•+*]\s*/, '').trim())
      .filter((s) => /^(?:Dữ\s*kiện\s*:|Bước\s*\d+)/i.test(s));
    if (rawParts.length >= 2) {
      return rawParts;
    }
  }

  const parseNum = (raw?: string): number | null => {
    if (!raw) return null;
    const n = parseFloat(raw.replace(/\s+/g, '').replace(',', '.'));
    return Number.isFinite(n) ? n : null;
  };

  const fmt = (n: number): string => {
    const rounded = Math.round(n * 10000) / 10000;
    return String(rounded).replace('.', ',');
  };

  // =========================================================================
  // 1. CONCRETE SOLVER: OHM'S LAW & ELECTRIC CIRCUITS (U, R, R1, R2, I, P, Q)
  // =========================================================================
  if (/(ohm|điện trở|cường độ dòng điện|hiệu điện thế|công suất điện|mạch điện)/i.test(qLower)) {
    const uMatch = question.match(/U\s*=\s*(\d+(?:[.,]\d+)?)\s*V/i);
    const r1Match = question.match(/R[₁1]\s*=\s*(\d+(?:[.,]\d+)?)\s*Ω/i);
    const r2Match = question.match(/R[₂2]\s*=\s*(\d+(?:[.,]\d+)?)\s*Ω/i);
    const rSingleMatch = question.match(/R\s*=\s*(\d+(?:[.,]\d+)?)\s*Ω/i);
    const tMinMatch = question.match(/(\d+(?:[.,]\d+)?)\s*phút/i);
    const tSecMatch = question.match(/t\s*=\s*(\d+(?:[.,]\d+)?)\s*(?:s|giây)/i);

    const U = parseNum(uMatch?.[1]);
    const R1 = parseNum(r1Match?.[1]);
    const R2 = parseNum(r2Match?.[1]);
    const R = parseNum(rSingleMatch?.[1]);
    const tSec = tMinMatch ? (parseNum(tMinMatch[1]) || 0) * 60 : parseNum(tSecMatch?.[1]);

    if (U !== null && R1 !== null && R2 !== null) {
      const isParallel = /song song/i.test(qLower);
      if (isParallel) {
        const Rtd = (R1 * R2) / (R1 + R2);
        const I1 = U / R1;
        const I2 = U / R2;
        const I = I1 + I2;
        const P = U * I;
        const duKienParts = [
          `R₁ = ${fmt(R1)} Ω`,
          `R₂ = ${fmt(R2)} Ω`,
          `U = ${fmt(U)} V`,
          tSec ? `t = ${fmt(tSec)} s` : `Mạch mắc: R₁ // R₂`,
        ];
        const steps = [
          `Dữ kiện: ${duKienParts.join(' | ')}`,
          `Bước 1 (a) Điện trở tương đương của đoạn mạch song song): Hai điện trở mắc song song (R₁ // R₂) nên:\n[EQ] R_{tđ} = \\frac{R₁ × R₂}{R₁ + R₂} = \\frac{${fmt(R1)} × ${fmt(R2)}}{${fmt(R1)} + ${fmt(R2)}} = ${fmt(Rtd)} Ω`,
          `Bước 2 (b) Cường độ dòng điện qua mỗi điện trở và mạch chính): Do mạch mắc song song nên U₁ = U₂ = U = ${fmt(U)} V:\n[EQ] I₁ = \\frac{U}{R₁} = \\frac{${fmt(U)}}{${fmt(R1)}} = ${fmt(I1)} A ;   I₂ = \\frac{U}{R₂} = \\frac{${fmt(U)}}{${fmt(R2)}} = ${fmt(I2)} A\nCường độ dòng điện mạch chính:\n[EQ] I = I₁ + I₂ = ${fmt(I1)} + ${fmt(I2)} = ${fmt(I)} A`,
        ];
        if (tSec) {
          const Q = U * I * tSec;
          steps.push(
            `Bước 3 (c) Nhiệt lượng tỏa ra trên toàn mạch): Nhiệt lượng tỏa ra trên đoạn mạch trong thời gian t = ${fmt(tSec)} s là:\n[EQ] Q = U × I × t = ${fmt(U)} × ${fmt(I)} × ${fmt(tSec)} = ${fmt(Q)} J`
          );
        } else {
          steps.push(
            `Bước 3 (c) Công suất tiêu thụ của đoạn mạch): Công suất tiêu thụ điện của toàn mạch là:\n[EQ] P = U × I = ${fmt(U)} × ${fmt(I)} = ${fmt(P)} W`
          );
        }
        return steps;
      } else {
        const Rtd = R1 + R2;
        const I = U / Rtd;
        const P = U * I;
        return [
          `Dữ kiện: R₁ = ${fmt(R1)} Ω | R₂ = ${fmt(R2)} Ω | U = ${fmt(U)} V | Mạch mắc: R₁ nt R₂`,
          `Bước 1 (a) Điện trở tương đương của đoạn mạch nối tiếp): Hai điện trở mắc nối tiếp nên điện trở tương đương của đoạn mạch là:\n[EQ] R_{tđ} = R₁ + R₂ = ${fmt(R1)} + ${fmt(R2)} = ${fmt(Rtd)} Ω`,
          `Bước 2 (b) Cường độ dòng điện chạy trong mạch): Áp dụng Định luật Ohm cho toàn mạch:\n[EQ] I = \\frac{U}{R_{tđ}} = \\frac{${fmt(U)}}{${fmt(Rtd)}} = ${fmt(I)} A`,
          `Bước 3 (c) Công suất tiêu thụ điện của đoạn mạch): Công suất tiêu thụ điện của cả đoạn mạch là:\n[EQ] P = U × I = ${fmt(U)} × ${fmt(I)} = ${fmt(P)} W`,
        ];
      }
    }

    if (U !== null && R !== null) {
      const I = U / R;
      const P = U * I;
      return [
        `Dữ kiện: U = ${fmt(U)} V | R = ${fmt(R)} Ω`,
        `Bước 1 (a) Công thức Định luật Ohm): Cường độ dòng điện chạy qua dây dẫn tỉ lệ thuận với hiệu điện thế và tỉ lệ nghịch với điện trở:\n[EQ] I = \\frac{U}{R}`,
        `Bước 2 (b) Thay số tính cường độ dòng điện): Thay U = ${fmt(U)} V và R = ${fmt(R)} Ω vào công thức:\n[EQ] I = \\frac{U}{R} = \\frac{${fmt(U)}}{${fmt(R)}} = ${fmt(I)} A${qLower.includes('công suất') ? `\n[EQ] P = U × I = ${fmt(U)} × ${fmt(I)} = ${fmt(P)} W` : ''}`,
        isEssay
          ? `Bước 3 (c) Kết luận): Vậy cường độ dòng điện chạy qua dây dẫn là I = ${fmt(I)} A.`
          : `Bước 3 (c) Kết luận đáp án): Đối chiếu kết quả I = ${fmt(I)} A ⇒ Chọn đáp án ${letter} (${correctText}).`,
      ];
    }
  }

  // =========================================================================
  // 2. CONCRETE SOLVER: CHEMISTRY STOICHIOMETRY (Metal + Acid -> Salt + H2)
  // =========================================================================
  if (/(gam|mol|lít|ml)\b/i.test(qLower) && /(hcl|hydrochloric|h2so4|sulfuric|iron|fe\b|zinc|zn\b|magnesium|mg\b|aluminium|al\b)/i.test(qLower)) {
    const massMatch = question.match(/(\d+(?:[.,]\d+)?)\s*(?:gam|g\b)/i);
    const volMlMatch = question.match(/(\d+(?:[.,]\d+)?)\s*mL/i);
    const m = parseNum(massMatch?.[1]);
    const vMl = parseNum(volMlMatch?.[1]);

    let metalSymbol = 'Fe';
    let metalName = 'Iron (Fe)';
    let molarMass = 56;
    let saltFormula = 'FeCl₂';
    let saltMolarMass = 127;
    let eq = 'Fe + 2HCl → FeCl₂ + H₂↑';
    let hclRatio = 2;
    let h2Ratio = 1;

    if (/(zinc|\bzn\b|kẽm)/i.test(qLower)) {
      metalSymbol = 'Zn';
      metalName = 'Zinc (Zn)';
      molarMass = 65;
      saltFormula = 'ZnCl₂';
      saltMolarMass = 136;
      eq = 'Zn + 2HCl → ZnCl₂ + H₂↑';
    } else if (/(magnesium|\bmg\b|magie)/i.test(qLower)) {
      metalSymbol = 'Mg';
      metalName = 'Magnesium (Mg)';
      molarMass = 24;
      saltFormula = 'MgCl₂';
      saltMolarMass = 95;
      eq = 'Mg + 2HCl → MgCl₂ + H₂↑';
    } else if (/(aluminium|\bal\b|nhôm)/i.test(qLower)) {
      metalSymbol = 'Al';
      metalName = 'Aluminium (Al)';
      molarMass = 27;
      saltFormula = 'AlCl₃';
      saltMolarMass = 133.5;
      eq = '2Al + 6HCl → 2AlCl₃ + 3H₂↑';
      hclRatio = 3;
      h2Ratio = 1.5;
    }

    if (m !== null) {
      const nMetal = m / molarMass;
      const nH2 = nMetal * h2Ratio;
      const vH2 = nH2 * 24.79;
      const nAcid = nMetal * hclRatio;
      const mSalt = nMetal * saltMolarMass;

      const vL = vMl !== null ? vMl / 1000 : null;
      const duKienItems = [
        `m(${metalSymbol}) = ${fmt(m)} g`,
        `M(${metalSymbol}) = ${molarMass} g/mol`,
        vL !== null
          ? `V(dd HCl) = ${fmt(vMl!)} mL = ${fmt(vL)} L`
          : `M(${saltFormula}) = ${fmt(saltMolarMass)} g/mol`,
        `Vₘ = 24,79 L/mol (25°C, 1 bar)`,
      ];

      const step1 = `Bước 1 (a) Phương trình hóa học):\n[EQ] ${eq}\nSố mol ${metalName} đã phản ứng:\n[EQ] n_{${metalSymbol}} = \\frac{m_{${metalSymbol}}}{M_{${metalSymbol}}} = \\frac{${fmt(m)}}{${molarMass}} = ${fmt(nMetal)} mol`;
      const step2 = `Bước 2 (b) Thể tích khí hydrogen (H₂) thu được): Theo phương trình hóa học, tỉ lệ mol ${metalSymbol} : H₂ = 1 : ${fmt(h2Ratio)}, nên:\n[EQ] n_{H₂} = ${h2Ratio === 1 ? '' : `${fmt(h2Ratio)} × `}n_{${metalSymbol}} = ${fmt(nH2)} mol\nThể tích khí H₂ ở điều kiện chuẩn (25°C, 1 bar):\n[EQ] V_{H₂} = n_{H₂} × 24,79 = ${fmt(nH2)} × 24,79 = ${fmt(vH2)} L`;

      if (vL !== null) {
        const cm = nAcid / vL;
        return [
          `Dữ kiện: ${duKienItems.join(' | ')}`,
          step1,
          step2,
          `Bước 3 (c) Nồng độ mol của dung dịch HCl): Theo phương trình hóa học, tỉ lệ mol ${metalSymbol} : HCl = 1 : ${hclRatio}, nên:\n[EQ] n_{HCl} = ${hclRatio} × n_{${metalSymbol}} = ${hclRatio} × ${fmt(nMetal)} = ${fmt(nAcid)} mol\nNồng độ mol của dung dịch HCl:\n[EQ] C_{M}(HCl) = \\frac{n_{HCl}}{V_{dd}} = \\frac{${fmt(nAcid)}}{${fmt(vL)}} = ${fmt(cm)} mol/L = ${fmt(cm)} M`,
        ];
      }

      if (/khối lượng muối/i.test(qLower)) {
        return [
          `Dữ kiện: ${duKienItems.join(' | ')}`,
          step1,
          step2,
          `Bước 3 (c) Khối lượng muối ${saltFormula} tạo thành): Theo phương trình hóa học, số mol muối là:\n[EQ] n_{${saltFormula}} = n_{${metalSymbol}} = ${fmt(nMetal)} mol\nKhối lượng muối ${saltFormula} thu được:\n[EQ] m_{${saltFormula}} = n_{${saltFormula}} × M_{${saltFormula}} = ${fmt(nMetal)} × ${fmt(saltMolarMass)} = ${fmt(mSalt)} g`,
        ];
      }

      return [
        `Dữ kiện: ${duKienItems.join(' | ')}`,
        step1,
        step2,
        `Bước 3 (c) Kết luận): Vậy thể tích khí Hydrogen (H₂) thu được ở đkc (25°C, 1 bar) là V = ${fmt(vH2)} L${!isEssay ? ` ⇒ Chọn đáp án ${letter} (${correctText}).` : '.'}`,
      ];
    }
  }

  // =========================================================================
  // 3. CONCRETE SOLVER: ATOMIC STRUCTURE (Z, Proton, Neutron, Electron, amu)
  // =========================================================================
  if (/(proton|neutron|electron|hạt nhân|rutherford|bohr|điện tích hạt nhân)/i.test(qLower)) {
    const zMatch = question.match(/Z\s*=\s*(\d+)/i);
    const nMatch = question.match(/Neutron(?:\s+trong\s+hạt\s+nhân)?\s+là\s+(\d+)|n\s*=\s*(\d+)/i);
    const Z = zMatch ? parseInt(zMatch[1], 10) : null;
    const N = nMatch ? parseInt(nMatch[1] || nMatch[2], 10) : null;

    if (Z !== null) {
      const k = Math.min(2, Z);
      const l = Math.min(8, Math.max(0, Z - 2));
      const mShell = Math.max(0, Z - 10);
      const shellStr = mShell > 0 ? `${k} - ${l} - ${mShell}` : l > 0 ? `${k} - ${l}` : `${k}`;
      const A = N !== null ? Z + N : Z * 2;
      return [
        `Dữ kiện: Điện tích hạt nhân Z = ${Z} | ${N !== null ? `Số hạt Neutron n = ${N}` : 'Nguyên tử trung hòa về điện (p = e)'}`,
        `Bước 1 (a) Xác định số hạt Proton và Electron): Nguyên tử trung hòa về điện nên số hạt Proton bằng số hạt Electron:\n[EQ] p = e = Z = ${Z} (hạt)`,
        N !== null
          ? `Bước 2 (b) Tính khối lượng nguyên tử theo amu): Khối lượng nguyên tử tập trung ở hạt nhân:\n[EQ] A ≈ p + n = ${Z} + ${N} = ${A} amu`
          : `Bước 2 (b) Cấu tạo hạt nhân và vỏ nguyên tử): Hạt nhân gồm ${Z} hạt Proton (điện tích +1); vỏ nguyên tử gồm ${Z} hạt Electron (điện tích -1).`,
        `Bước 3 (c) Phân bố electron vào các lớp vỏ): Phân bố ${Z} electron theo thứ tự từ trong ra ngoài:\n[EQ] Lớp K: ${k}e${l > 0 ? `  |  Lớp L: ${l}e` : ''}${mShell > 0 ? `  |  Lớp M (ngoài cùng): ${mShell}e` : ''}  (${shellStr})`,
      ];
    }

    return [
      `Dữ kiện: Mô hình nguyên tử: Rutherford – Bohr | p (+1), n (0), e (-1)`,
      `Bước 1 (a) Cấu tạo hạt nhân nguyên tử): Trong mô hình nguyên tử Rutherford – Bohr, hạt nhân nằm ở tâm nguyên tử gồm các hạt Proton (p, mang điện tích dương +1) và hạt Neutron (n, không mang điện).`,
      `Bước 2 (b) Cấu tạo lớp vỏ nguyên tử): Lớp vỏ nguyên tử gồm các hạt Electron (e, mang điện tích âm -1) chuyển động xung quanh hạt nhân:\n[EQ] Số hạt Proton (p) = Số hạt Electron (e) = Z`,
      isEssay
        ? `Bước 3 (c) Kết luận): Nguyên tử gồm hạt nhân (Proton + Neutron) và lớp vỏ chứa các hạt Electron.`
        : `Bước 3 (c) Kết luận đáp án): Đối chiếu với đề bài ⇒ Chọn đáp án ${letter} (${correctText}).`,
    ];
  }

  // =========================================================================
  // 4. CONCRETE SOLVER: SPEED (v = s / t) & PRESSURE (p = F / S)
  // =========================================================================
  if (/(tốc độ|quãng đường|chuyển động đều)/i.test(qLower)) {
    const sKmMatch = question.match(/(\d+(?:[.,]\d+)?)\s*km/i);
    const sMMatch = question.match(/(\d+(?:[.,]\d+)?)\s*m\b/i);
    const tMinMatch = question.match(/(\d+(?:[.,]\d+)?)\s*phút/i);
    const tSecMatch = question.match(/(\d+(?:[.,]\d+)?)\s*(?:giây|s\b)/i);

    const sMeters = sKmMatch
      ? (parseNum(sKmMatch[1]) || 0) * 1000
      : parseNum(sMMatch?.[1]);
    const tSeconds = tMinMatch
      ? (parseNum(tMinMatch[1]) || 0) * 60
      : parseNum(tSecMatch?.[1]);

    if (sMeters && tSeconds) {
      const v = sMeters / tSeconds;
      return [
        `Dữ kiện: s = ${sKmMatch ? `${sKmMatch[1]} km = ` : ''}${fmt(sMeters)} m | t = ${tMinMatch ? `${tMinMatch[1]} phút = ` : ''}${fmt(tSeconds)} s`,
        `Bước 1 (a) Đổi đơn vị về hệ chuẩn SI): Quãng đường di chuyển và thời gian chuyển động:\n[EQ] s = ${fmt(sMeters)} m ;   t = ${fmt(tSeconds)} s`,
        `Bước 2 (b) Tính tốc độ chuyển động): Áp dụng công thức tính tốc độ:\n[EQ] v = \\frac{s}{t} = \\frac{${fmt(sMeters)}}{${fmt(tSeconds)}} = ${fmt(v)} m/s`,
        `Bước 3 (c) Kết luận): Vậy tốc độ cần tìm là v = ${fmt(v)} m/s${!isEssay ? ` ⇒ Chọn đáp án ${letter} (${correctText}).` : '.'}`,
      ];
    }
  }

  if (/(áp suất|áp lực)/i.test(qLower)) {
    const fMatch = question.match(/F\s*=\s*(\d+(?:[.,]\d+)?)\s*N/i);
    const sMatch = question.match(/S\s*=\s*(\d+(?:[.,]\d+)?)\s*m[²2]/i);
    const F = parseNum(fMatch?.[1]);
    const S = parseNum(sMatch?.[1]);
    if (F !== null && S !== null && S > 0) {
      const p = F / S;
      return [
        `Dữ kiện: Áp lực F = ${fmt(F)} N | Diện tích bị ép S = ${fmt(S)} m²`,
        `Bước 1 (a) Công thức tính áp suất): Áp suất được tính bằng độ lớn của áp lực trên một đơn vị diện tích bị ép:\n[EQ] p = \\frac{F}{S}`,
        `Bước 2 (b) Thay số tính áp suất): Thay F = ${fmt(F)} N và S = ${fmt(S)} m² vào công thức:\n[EQ] p = \\frac{F}{S} = \\frac{${fmt(F)}}{${fmt(S)}} = ${fmt(p)} N/m² = ${fmt(p)} Pa`,
        `Bước 3 (c) Kết luận): Vậy áp suất tác dụng lên mặt sàn là p = ${fmt(p)} Pa${!isEssay ? ` ⇒ Chọn đáp án ${letter} (${correctText}).` : '.'}`,
      ];
    }
  }

  // =========================================================================
  // 5. CONCRETE SOLVER: DNA STRUCTURE (N, A, T, G, C, Hydrogen bonds H)
  // =========================================================================
  if (/(dna|nucleotide|adenine|thymine|guanine|cytosine|liên kết hydrogen)/i.test(qLower)) {
    const nTotalMatch = question.match(/N\s*=\s*(\d+)/i);
    const aMatch = question.match(/(?:Adenine\s*\(?A\)?|A)\s*=\s*(\d+)/i);
    const N = nTotalMatch ? parseInt(nTotalMatch[1], 10) : null;
    const A = aMatch ? parseInt(aMatch[1], 10) : null;

    if (N !== null && A !== null) {
      const G = (N - 2 * A) / 2;
      const H = 2 * A + 3 * G;
      return [
        `Dữ kiện: Tổng số Nucleotide N = ${N} | A = ${A} Nucleotide`,
        `Bước 1 (a) Áp dụng nguyên tắc bổ sung): Trong phân tử DNA mạch kép, Adenine liên kết với Thymine và Guanine liên kết với Cytosine:\n[EQ] A = T = ${A} (Nucleotide) ;   G = C`,
        `Bước 2 (b) Tính số lượng Nucleotide từng loại): Ta có tổng số Nucleotide của phân tử DNA là N = 2A + 2G = ${N}, suy ra:\n[EQ] G = C = \\frac{N - 2A}{2} = \\frac{${N} - 2 × ${A}}{2} = \\frac{${N - 2 * A}}{2} = ${G} (Nucleotide)`,
        `Bước 3 (c) Tính tổng số liên kết Hydrogen): Vì A liên kết với T bằng 2 liên kết Hydrogen và G liên kết với C bằng 3 liên kết Hydrogen:\n[EQ] H = 2A + 3G = 2 × ${A} + 3 × ${G} = ${2 * A} + ${3 * G} = ${H} (liên kết)`,
      ];
    }

    return [
      `Dữ kiện: A liên kết T: 2 liên kết Hydrogen | G liên kết C: 3 liên kết Hydrogen`,
      `Bước 1 (a) Nguyên tắc bổ sung trong phân tử DNA): Hai mạch đơn của phân tử DNA xoắn kép liên kết với nhau bằng các liên kết Hydrogen giữa các base nitơ:\n[EQ] A - T (2 liên kết Hydrogen) ;   G ≡ C (3 liên kết Hydrogen)`,
      `Bước 2 (b) Hệ quả về số lượng Nucleotide): Do A luôn bắt cặp với T và G luôn bắt cặp với C nên:\n[EQ] A = T ;   G = C ;   N = 2A + 2G ;   H = 2A + 3G`,
      isEssay
        ? `Bước 3 (c) Kết luận): Tổng số Nucleotide N = 2A + 2G và tổng số liên kết Hydrogen H = 2A + 3G.`
        : `Bước 3 (c) Kết luận đáp án): Đối chiếu nguyên tắc bổ sung ⇒ Chọn đáp án ${letter} (${correctText}).`,
    ];
  }

  // =========================================================================
  // 6. CONCRETE SOLVER: ACID - BASE - pH & CHEMICAL REACTIONS
  // =========================================================================
  if (/(acid|base|ph\b|phenolphthalein|quỳ tím|naoh|hcl|h2so4|ca\(oh\)2|ester|acetic)/i.test(qLower)) {
    if (/acetic|ethylic|ester/i.test(qLower)) {
      return [
        `Dữ kiện: Chất tham gia: CH₃COOH, C₂H₅OH | Xúc tác: H₂SO₄ đặc, t°`,
        `Bước 1 (a) Phương trình hóa học phản ứng ester hóa):\n[EQ] CH₃COOH + C₂H₅OH ⇄ CH₃COOC₂H₅ + H₂O   (H₂SO₄ đặc, t°)`,
        `Bước 2 (b) Gọi tên sản phẩm theo danh pháp IUPAC): Phân tử CH₃COOC₂H₅ gồm gốc Ethyl (-C₂H₅) và gốc acetate (CH₃COO⁻) nên có tên gọi chuẩn IUPAC là Ethyl acetate.`,
        `Bước 3 (c) Kết luận): Chất thu được là Ethyl acetate (CH₃COOC₂H₅)${!isEssay ? ` ⇒ Chọn đáp án ${letter}.` : '.'}`,
      ];
    }

    if (/phenolphthalein|naoh|ca\(oh\)2|base/i.test(qLower)) {
      return [
        `Dữ kiện: Dung dịch Base kiềm: NaOH, Ca(OH)₂ | Môi trường Base: pH > 7`,
        `Bước 1 (a) Phân tích tính chất dung dịch Base): Dung dịch Sodium hydroxide (NaOH) và Calcium hydroxide (Ca(OH)₂) là các Base tan (kiềm), phân li ra ion OH⁻:\n[EQ] NaOH → Na⁺ + OH⁻   (pH > 7)`,
        `Bước 2 (b) Hiện tượng đổi màu chất chỉ thị): Trong môi trường Base (pH > 7), dung dịch Phenolphthalein từ không màu chuyển sang màu hồng cánh sen (giấy quỳ tím chuyển sang màu xanh lam).`,
        isEssay
          ? `Bước 3 (c) Kết luận): Dung dịch chuyển sang màu hồng cánh sen do môi trường Base (pH > 7).`
          : `Bước 3 (c) Kết luận đáp án): Vậy phương án đúng là ${correctText} ⇒ Chọn đáp án ${letter}.`,
      ];
    }

    return [
      `Dữ kiện: Môi trường Acid: pH < 7 | Môi trường Trung tính: pH = 7 | Môi trường Base: pH > 7`,
      `Bước 1 (a) Xác định môi trường dung dịch theo thang pH): Dung dịch Acid (HCl, H₂SO₄) tạo ra ion H⁺ trong nước:\n[EQ] HCl → H⁺ + Cl⁻   ⇒   pH < 7 (quỳ tím hóa đỏ)`,
      `Bước 2 (b) So sánh với môi trường trung tính và Base): Dung dịch trung tính có pH = 7; dung dịch Base kiềm có pH > 7.`,
      `Bước 3 (c) Kết luận đáp án): Vậy đáp án đúng là ${letter} (${correctText}).`,
    ];
  }

  // =========================================================================
  // 7. SPECIFIC SOLUTION FROM EXISTING EXPLANATION OR ANSWER CHOICE
  // =========================================================================
  if (existingExplanation && existingExplanation.trim().length > 5) {
    const cleanExp = existingExplanation.trim();
    const sentences = cleanExp
      .split(/(?<=[.?!;])\s+/)
      .map((s) => s.trim())
      .filter(Boolean);
    if (sentences.length >= 2) {
      return sentences.map((s, idx) => `Bước ${idx + 1}: ${s}`);
    }
    return [
      `Bước 1 (a) Phân tích bài toán): ${cleanExp}`,
      isEssay
        ? `Bước 2 (b) Kết luận): Hoàn thành bài giải.`
        : `Bước 2 (b) Kết luận đáp án): Vậy đáp án đúng là ${letter} (${correctText}).`,
    ];
  }

  return [
    `Bước 1 (a) Phân tích đề bài): ${question}`,
    `Bước 2 (b) Xác định kết quả đúng): ${correctText || 'Theo lời giải chi tiết bài toán'}.`,
    isEssay
      ? `Bước 3 (c) Kết luận): Kết luận đáp số bài toán.`
      : `Bước 3 (c) Kết luận đáp án): Chọn đáp án ${letter} (${correctText}).`,
  ];
}

/**
 * Helper to parse any explanation string or explicit solutionSteps into an array of clean steps for UI rendering
 */
export function parseExplanationIntoSteps(
  explanation: string,
  explicitSteps?: string[],
  fallbackParams?: {
    question: string;
    options: string[];
    correctAnswer?: number;
    questionType?: QuestionType;
    domain?: SubjectDomain;
    grade?: Grade;
  }
): string[] {
  if (Array.isArray(explicitSteps) && explicitSteps.length > 0) {
    return explicitSteps;
  }

  if (explanation && /Bước\s*1\s*[:(-]/i.test(explanation)) {
    const steps = explanation
      .split(/\n(?=(?:Dữ\s*kiện\s*:|[-•+]\s*Bước\s*\d+|Bước\s*\d+\s*[:(-]))/i)
      .map((s) => s.replace(/^[-•+*]\s*/, '').trim())
      .filter((s) => /^(?:Dữ\s*kiện\s*:|Bước\s*\d+)/i.test(s));
    if (steps.length >= 2) {
      return steps;
    }
  }

  if (fallbackParams) {
    return generateStepByStepSolution({
      question: fallbackParams.question,
      options: fallbackParams.options,
      correctAnswer: fallbackParams.correctAnswer,
      questionType: fallbackParams.questionType,
      domain: fallbackParams.domain || 'hoa-hoc',
      grade: fallbackParams.grade || 8,
      existingExplanation: explanation,
    });
  }

  if (!explanation) return [];
  const sentences = explanation
    .split(/(?<=[.?!;])\s+/)
    .map((s) => s.trim())
    .filter(Boolean);
  if (sentences.length >= 2) {
    return sentences.map((s, idx) => `Bước ${idx + 1}: ${s}`);
  }
  return [`Bước 1: ${explanation}`];
}

/**
 * Generates a concrete worked-out solution string for a quiz question
 */
export function generateDetailedExplanation(params: {
  question: string;
  options: string[];
  correctAnswer: number;
  questionType?: QuestionType;
  domain: SubjectDomain;
  grade: Grade;
  existingExplanation?: string;
}): string {
  const steps = generateStepByStepSolution(params);
  const isEssay = params.questionType === 'essay' || params.options.length === 0;
  const letter = String.fromCharCode(
    65 + (params.correctAnswer >= 0 && params.correctAnswer < params.options.length ? params.correctAnswer : 0)
  );
  const correctText = !isEssay ? params.options[params.correctAnswer] || params.options[0] || '' : '';

  const header = isEssay
    ? `Lời giải chi tiết:`
    : `Đáp án đúng là ${letter} (${correctText}).`;

  return `${header}\n${steps.join('\n')}`;
}

/**
 * Extracts global answer table at the end of a Word document if present
 * e.g. "1.A  2.B  3.C  4.D" or "1-A, 2-B, 3-C" or "Câu 1: A"
 */
function extractAnswerTableMap(text: string): Map<number, number> {
  const map = new Map<number, number>();
  const answerSectionMatch = text.match(/(?:BẢNG ĐÁP ÁN|ĐÁP ÁN CHI TIẾT|ĐÁP ÁN\s*:?)\s*([\s\S]*)$/i);
  const targetZone = answerSectionMatch ? answerSectionMatch[1] : '';
  if (!targetZone) return map;

  const pairRegex = /(?:Câu\s*)?(\d{1,3})\s*[.:\-)\s]\s*([A-D])\b/gi;
  let match: RegExpExecArray | null;
  while ((match = pairRegex.exec(targetZone)) !== null) {
    const qNum = parseInt(match[1], 10);
    const ansChar = match[2].toUpperCase();
    const ansIdx = ansChar.charCodeAt(0) - 65;
    if (qNum > 0 && ansIdx >= 0 && ansIdx <= 3) {
      map.set(qNum, ansIdx);
    }
  }
  return map;
}

/**
 * Extracts bold/underlined option markers from HTML converted by mammoth
 */
function extractFormattedCorrectOptionMap(html?: string): Map<number, number> {
  const map = new Map<number, number>();
  if (!html) return map;

  const blocks = html.split(/(?=(?:Câu|Bài|Question)\s+\d+)/i);
  blocks.forEach((block, idx) => {
    const qNumMatch = block.match(/(?:Câu|Bài|Question)\s+(\d+)/i);
    const qNum = qNumMatch ? parseInt(qNumMatch[1], 10) : idx + 1;

    const formattedOptMatch = block.match(/<(?:strong|b|u|em|mark)[^>]*>\s*\*?\s*([A-D])\s*[.)]/i);
    if (formattedOptMatch) {
      const letter = formattedOptMatch[1].toUpperCase();
      map.set(qNum, letter.charCodeAt(0) - 65);
    }
  });

  return map;
}

/**
 * Main parser: Converts raw Word text (and optional HTML) into web QuizQuestion format
 * with guaranteed step-by-step explanations and automatic detection of Essay (Tự luận) questions.
 */
export function parseWordContentToQuestions(
  rawText: string,
  options: WordParseOptions = {}
): ParsedWordQuestionResult {
  const {
    htmlContent,
    defaultGrade = 8,
    defaultDomain = 'hoa-hoc',
    defaultLessonId,
    autoStandardizeIupac = true,
  } = options;

  const warnings: string[] = [];
  if (!rawText || !rawText.trim()) {
    return {
      questions: [],
      warnings: ['Nội dung tệp Word trống hoặc không có văn bản câu hỏi.'],
      stats: { totalParsed: 0, autoExplainedCount: 0, iupacNormalizedCount: 0, essayCount: 0 },
    };
  }

  const normalizedText = rawText.replace(/\r\n/g, '\n').replace(/\r/g, '\n');

  // 1. Extract global answer table if placed at the bottom of the document
  const globalAnswerMap = extractAnswerTableMap(normalizedText);
  const htmlFormattedMap = extractFormattedCorrectOptionMap(htmlContent);

  const bodyWithoutAnswerTable = normalizedText.replace(
    /\n\s*(?:BẢNG ĐÁP ÁN|ĐÁP ÁN THAM KHẢO)\s*\n[\s\S]*$/i,
    ''
  );

  // 2. Split into question blocks while tracking whether we are inside a "TỰ LUẬN" section
  const lines = bodyWithoutAnswerTable.split('\n');
  const questionBlocks: Array<{
    qNumber: number;
    headerLine: string;
    bodyLines: string[];
    inEssaySection: boolean;
    explicitEssayTag: boolean;
  }> = [];

  const questionStartRegex =
    /^\s*(?:(?:Câu|Bài|Question)\s*(\d+)\s*(\([^)]*\)|\[[^\]]*\])?\s*[:.)-]?\s*|(\d+)\s*[.)]\s+)(.*)$/i;

  let currentBlock: {
    qNumber: number;
    headerLine: string;
    bodyLines: string[];
    inEssaySection: boolean;
    explicitEssayTag: boolean;
  } | null = null;
  let isCurrentlyInEssaySection = false;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;

    // Detect transition to Essay section ("PHẦN II. TỰ LUẬN", "II. TỰ LUẬN", "B. TỰ LUẬN")
    if (/^(?:PHẦN\s*(?:II|2|B)|II\.|B\.)\s*[:.-]?\s*TỰ\s*LUẬN|^TỰ\s*LUẬN\b/i.test(line)) {
      isCurrentlyInEssaySection = true;
      continue;
    }

    // Detect transition to Multiple Choice section
    if (/^(?:PHẦN\s*(?:I|1|A)|I\.|A\.)\s*[:.-]?\s*TRẮC\s*NGHIỆM/i.test(line)) {
      isCurrentlyInEssaySection = false;
      continue;
    }

    // Skip common exam header titles
    if (
      !currentBlock &&
      /^(?:ĐỀ KIỂM TRA|TRƯỜNG THCS|MÔN:\s*KHOA HỌC TỰ NHIÊN|THỜI GIAN LÀM BÀI|HỌ VÀ TÊN)/i.test(
        line
      )
    ) {
      continue;
    }

    const startMatch = line.match(questionStartRegex);
    // Avoid treating "- Bước 1." or "1. Bước" inside an explanation as a new question
    const looksLikeStepLine = /^(?:[-•+]\s*)?Bước\s*\d+/i.test(line);

    if (startMatch && !looksLikeStepLine) {
      const numStr = startMatch[1] || startMatch[3];
      const tagStr = startMatch[2] || '';
      const qNum = parseInt(numStr, 10);
      const remainder = startMatch[4] || '';
      if (currentBlock) {
        questionBlocks.push(currentBlock);
      }
      const explicitEssay = /tự\s*luận|essay/i.test(tagStr) || /tự\s*luận/i.test(remainder);
      currentBlock = {
        qNumber: qNum || questionBlocks.length + 1,
        headerLine: remainder.replace(/^\s*\(?tự\s*luận\)?\s*[:.-]?\s*/i, ''),
        bodyLines: [],
        inEssaySection: isCurrentlyInEssaySection,
        explicitEssayTag: explicitEssay,
      };
    } else if (currentBlock) {
      currentBlock.bodyLines.push(line);
    }
  }
  if (currentBlock) {
    questionBlocks.push(currentBlock);
  }

  // Fallback if no numbered headers found
  if (questionBlocks.length === 0 && bodyWithoutAnswerTable.trim()) {
    const nonEmptyLines = lines.map((l) => l.trim()).filter(Boolean);
    if (nonEmptyLines.length > 0) {
      questionBlocks.push({
        qNumber: 1,
        headerLine: nonEmptyLines[0],
        bodyLines: nonEmptyLines.slice(1),
        inEssaySection: false,
        explicitEssayTag: false,
      });
    }
  }

  const parsedQuestions: ParsedWordQuestion[] = [];
  let autoExplainedCount = 0;
  let iupacNormalizedCount = 0;
  let essayCount = 0;

  questionBlocks.forEach((block, idx) => {
    const fullBlockLines = [block.headerLine, ...block.bodyLines].filter(Boolean);

    let explicitCorrectIndex: number | null = null;
    let detectedSource: ParsedWordQuestion['detectedAnswerSource'] = 'default_first';
    const explanationLines: string[] = [];
    let extractedHint = '';
    let isCollectingExplanation = false;

    const cleanLines: string[] = [];
    for (const line of fullBlockLines) {
      const ansMatch = line.match(
        /^(?:Đáp\s*án(?:\s*đúng)?|ĐA|Chọn(?:\s*đáp\s*án)?|Key|Answer)\s*[:=-]?\s*\*?([A-D])\b(.*)$/i
      );
      if (ansMatch) {
        explicitCorrectIndex = ansMatch[1].toUpperCase().charCodeAt(0) - 65;
        detectedSource = 'explicit_key';
        const trailingExp = ansMatch[2]?.replace(/^[\s.,;-]+/, '').trim();
        if (trailingExp && trailingExp.length > 5) {
          explanationLines.push(trailingExp);
        }
        continue;
      }

      const expMatch = line.match(
        /^(?:Lời\s*giải(?:\s*chi\s*tiết)?|Giải\s*thích(?:\s*chi\s*tiết)?|Hướng\s*dẫn(?:\s*giải)?|Đáp\s*án\s*tự\s*luận|HDG|Explanation)\s*[:=-]?\s*(.*)$/i
      );
      if (expMatch) {
        isCollectingExplanation = true;
        if (expMatch[1]?.trim()) {
          explanationLines.push(expMatch[1].trim());
        }
        continue;
      }

      const hintMatch = line.match(/^(?:Gợi\s*ý|Hint)\s*[:=-]?\s*(.+)$/i);
      if (hintMatch) {
        extractedHint = hintMatch[1].trim();
        continue;
      }

      if (
        isCollectingExplanation &&
        /^(?:[-•+*]?\s*(?:Dữ\s*kiện\s*:|Bước\s*\d+)|\[EQ\]|[-•+]\s+)/i.test(line)
      ) {
        explanationLines.push(line.replace(/^[-•+*]\s*/, '').trim());
        continue;
      }

      cleanLines.push(line);
    }

    let extractedExplanation = explanationLines.join('\n').trim();
    const textForOptions = cleanLines.join('\n');

    // Parse options A, B, C, D
    const optionRegex = /(?:^|\n|\s{2,}|\t)(\*?)\s*([A-D])(\*?)\s*[.:)]\s*/g;
    const matches: Array<{
      letter: string;
      starred: boolean;
      matchStart: number;
      contentStart: number;
    }> = [];

    let m: RegExpExecArray | null;
    while ((m = optionRegex.exec(textForOptions)) !== null) {
      const fullMatch = m[0];
      const leadingOffset = fullMatch.search(/\*?\s*[A-D]\*?\s*[.:)]/);
      const actualStart = m.index + (leadingOffset >= 0 ? leadingOffset : 0);
      const letter = m[2].toUpperCase();
      const starred = m[1] === '*' || m[3] === '*';
      matches.push({
        letter,
        starred,
        matchStart: actualStart,
        contentStart: m.index + fullMatch.length,
      });
    }

    let questionStem = textForOptions;
    let rawOptions: string[] = [];
    let isEssayQuestion = block.inEssaySection || block.explicitEssayTag || matches.length < 2;

    if (!isEssayQuestion && matches.length >= 2) {
      questionStem = textForOptions.slice(0, matches[0].matchStart).trim();
      rawOptions = matches.map((item, i) => {
        const nextStart = i + 1 < matches.length ? matches[i + 1].matchStart : textForOptions.length;
        let optText = textForOptions.slice(item.contentStart, nextStart).trim();

        const inlineAnsMatch = optText.match(
          /\n?\s*(?:Đáp\s*án(?:\s*đúng)?|ĐA)\s*[:=-]?\s*([A-D])\b([\s\S]*)$/i
        );
        if (inlineAnsMatch) {
          if (explicitCorrectIndex === null) {
            explicitCorrectIndex = inlineAnsMatch[1].toUpperCase().charCodeAt(0) - 65;
            detectedSource = 'explicit_key';
          }
          optText = optText.slice(0, inlineAnsMatch.index).trim();
        }

        const inlineExpMatch = optText.match(
          /\n?\s*(?:Lời\s*giải|Giải\s*thích|Hướng\s*dẫn\s*giải)\s*[:=-]?\s*([\s\S]*)$/i
        );
        if (inlineExpMatch) {
          extractedExplanation = extractedExplanation || inlineExpMatch[1].trim();
          optText = optText.slice(0, inlineExpMatch.index).trim();
        }

        if (item.starred && explicitCorrectIndex === null) {
          explicitCorrectIndex = i;
          detectedSource = 'asterisk';
        }
        if (optText.startsWith('*')) {
          optText = optText.replace(/^\*+\s*/, '');
          if (explicitCorrectIndex === null) {
            explicitCorrectIndex = i;
            detectedSource = 'asterisk';
          }
        }
        return optText;
      });

      while (rawOptions.length > 2 && rawOptions.length < 4) {
        rawOptions.push(`Phương án ${String.fromCharCode(65 + rawOptions.length)}`);
      }
    } else {
      isEssayQuestion = true;
      rawOptions = [];
      detectedSource = 'essay_rubric';
      essayCount++;
    }

    // Apply IUPAC normalization if enabled
    let questionNormalized = questionStem;
    let normalizedOptions = [...rawOptions];
    if (autoStandardizeIupac) {
      const qNorm = normalizeChemicalNomenclature(questionStem);
      questionNormalized = qNorm.text;
      let anyChanged = qNorm.changed;
      normalizedOptions = rawOptions.map((opt) => {
        const oNorm = normalizeChemicalNomenclature(opt);
        if (oNorm.changed) anyChanged = true;
        return oNorm.text;
      });
      if (extractedExplanation) {
        const eNorm = normalizeChemicalNomenclature(extractedExplanation);
        if (eNorm.changed) anyChanged = true;
        extractedExplanation = eNorm.text;
      }
      if (anyChanged) {
        iupacNormalizedCount++;
      }
    }

    let finalCorrectIndex = 0;
    if (!isEssayQuestion) {
      let resolved = explicitCorrectIndex;
      if (resolved === null && globalAnswerMap.has(block.qNumber)) {
        resolved = globalAnswerMap.get(block.qNumber)!;
        detectedSource = 'answer_table';
      }
      if (resolved === null && htmlFormattedMap.has(block.qNumber)) {
        resolved = htmlFormattedMap.get(block.qNumber)!;
        detectedSource = 'formatting';
      }
      if (resolved === null) {
        const inferred = inferCorrectOptionFromKnowledge(questionNormalized, normalizedOptions);
        if (inferred !== null) {
          resolved = inferred;
          detectedSource = 'knowledge_inference';
        } else {
          resolved = 0;
          detectedSource = 'default_first';
        }
      }
      if (resolved < 0 || resolved >= normalizedOptions.length) {
        resolved = 0;
      }
      finalCorrectIndex = resolved;
    }

    const meta = detectDomainAndGrade(
      `${questionNormalized} ${normalizedOptions.join(' ')}`,
      defaultDomain,
      defaultGrade
    );

    const qType: QuestionType = isEssayQuestion
      ? 'essay'
      : normalizedOptions.length === 2 &&
        normalizedOptions.some((o) => /^đúng$/i.test(o.trim())) &&
        normalizedOptions.some((o) => /^sai$/i.test(o.trim()))
      ? 'true_false'
      : 'single_choice';

    const hadFullStepExplanation = Boolean(
      extractedExplanation && /Bước\s*1/i.test(extractedExplanation)
    );

    const solutionSteps = generateStepByStepSolution({
      question: questionNormalized,
      options: normalizedOptions,
      correctAnswer: finalCorrectIndex,
      questionType: qType,
      domain: meta.domain,
      grade: meta.grade,
      existingExplanation: extractedExplanation,
    });

    const detailedExplanation = generateDetailedExplanation({
      question: questionNormalized,
      options: normalizedOptions,
      correctAnswer: finalCorrectIndex,
      questionType: qType,
      domain: meta.domain,
      grade: meta.grade,
      existingExplanation: extractedExplanation,
    });

    if (!hadFullStepExplanation) {
      autoExplainedCount++;
    }

    parsedQuestions.push({
      id: `q-word-${Date.now()}-${idx + 1}`,
      lessonId: defaultLessonId,
      grade: meta.grade,
      domain: meta.domain,
      question: questionNormalized,
      questionType: qType,
      options: normalizedOptions,
      correctAnswer: finalCorrectIndex,
      explanation: detailedExplanation,
      solutionSteps,
      sampleAnswer: isEssayQuestion ? extractedExplanation || solutionSteps.join('\n') : undefined,
      allowImageUpload: isEssayQuestion ? true : undefined,
      difficulty: isEssayQuestion ? 'Vận dụng' : meta.difficulty,
      hint:
        extractedHint ||
        (isEssayQuestion
          ? `Câu hỏi tự luận KHTN Lớp ${meta.grade}: Em hãy trình bày từng bước công thức, thay số kèm đơn vị chuẩn hoặc chụp ảnh bài giải viết tay tải lên hệ thống.`
          : `Vận dụng kiến thức trọng tâm KHTN Lớp ${meta.grade} (${
              meta.domain === 'vat-li' ? 'Vật lí' : meta.domain === 'sinh-hoc' ? 'Sinh học' : 'Hóa học IUPAC'
            }).`),
      points: isEssayQuestion ? 2.5 : 1.5,
      autoGeneratedExplanation: !hadFullStepExplanation,
      detectedAnswerSource: detectedSource,
    });
  });

  return {
    questions: parsedQuestions,
    warnings,
    stats: {
      totalParsed: parsedQuestions.length,
      autoExplainedCount,
      iupacNormalizedCount,
      essayCount,
    },
  };
}

