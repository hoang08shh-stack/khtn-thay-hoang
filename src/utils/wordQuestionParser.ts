/**
 * Converts HTML <sub>...</sub> and <sup>...</sup> tags into Unicode subscripts/superscripts
 * or braced _{...} / ^{...} tokens so scientific notation is never lost.
 */
export function convertHtmlSubSupToUnicode(input: string): string {
  if (!input || !/<(?:sub|sup)\b/i.test(input)) return input;

  return input
    .replace(/<sub[^>]*>([\s\S]*?)<\/sub>/gi, (_m, inner: string) => {
      const clean = inner.replace(/<[^>]+>/g, '').trim();
      if (!clean) return '';
      if (/^[0-9+\-−()mnaeo]+$/.test(clean)) {
        return clean
          .split('')
          .map((ch) => SUBSCRIPT_MAP[ch] || ch)
          .join('');
      }
      return `_{${clean}}`;
    })
    .replace(/<sup[^>]*>([\s\S]*?)<\/sup>/gi, (_m, inner: string) => {
      const clean = inner.replace(/<[^>]+>/g, '').trim();
      if (!clean) return '';
      const normalizedCharge = clean.replace(/^([+-])(\d+)$/, '$2$1');
      if (/^[0-9+\-−()no°]+$/.test(normalizedCharge)) {
        return toSuperscriptChars(normalizedCharge);
      }
      return `^{${clean}}`;
    });
}

/**
 * Extracts structured plain text from Mammoth HTML while preserving <sub> and <sup>
 * indices as Unicode subscripts/superscripts, keeping <img> and <table> markers,
 * and maintaining paragraph breaks.
 */
export function extractFormattedTextFromMammothHtml(html: string, fallbackRawText = ''): string {
  if (!html || !html.trim()) return normalizeVietnameseUnicodeNFC(fallbackRawText);

  let working = convertWordOmmlToReadableFormula(html);
  working = convertHtmlSubSupToUnicode(working);

  // Preserve embedded images as [IMG:src] tokens before stripping HTML tags
  working = working.replace(/<img\b[^>]*?\bsrc=["']([^"']+)["'][^>]*>/gi, (_m, src: string) => {
    return `\n[IMG:${src.trim()}]\n`;
  });

  // Preserve data tables as [TABLE:base64OrEncoded] while also keeping their cell text for option parsing
  working = working.replace(/<table\b[^>]*>[\s\S]*?<\/table>/gi, (tableHtml: string) => {
    const cleanTable = convertHtmlSubSupToUnicode(tableHtml)
      .replace(/\r?\n/g, ' ')
      .replace(/\s{2,}/g, ' ')
      .trim();
    // Extract readable lines from table rows so options inside tables or data rows are also visible as text
    const rowTexts = [...tableHtml.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi)].map((rm) => {
      const cells = [...rm[1].matchAll(/<t[dh]\b[^>]*>([\s\S]*?)<\/t[dh]>/gi)].map((cm) =>
        convertHtmlSubSupToUnicode(cm[1])
          .replace(/<[^>]+>/g, '')
          .replace(/&nbsp;/gi, ' ')
          .trim()
      );
      return cells.filter(Boolean).join('   ');
    });
    // Check if the table is purely an A/B/C/D option layout table
    const joinedCells = rowTexts.join(' ');
    const isPureOptionTable =
      /\bA\s*[.:)]/.test(joinedCells) &&
      /\bB\s*[.:)]/.test(joinedCells) &&
      !/<th\b/i.test(tableHtml);

    if (isPureOptionTable) {
      return `\n${rowTexts.join('\n')}\n`;
    }
    const encodedTable = encodeURIComponent(cleanTable);
    return `\n[TABLE:${encodedTable}]\n${rowTexts.join('\n')}\n`;
  });

  working = working
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(?:p|div|li|tr|h[1-6])>/gi, '\n')
    .replace(/<\/(?:td|th)>/gi, '   ')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&rarr;|&#8594;/gi, '→')
    .replace(/&larr;|&#8592;/gi, '←')
    .replace(/&harr;|&#8596;|&#8652;/gi, '⇄')
    .replace(/&uarr;|&#8593;/gi, '↑')
    .replace(/&darr;|&#8595;/gi, '↓')
    .replace(/&deg;|&#176;/gi, '°')
    .replace(/&times;|&#215;/gi, '×')
    .replace(/&divide;|&#247;/gi, '÷')
    .replace(/&le;|&#8804;/gi, '≤')
    .replace(/&ge;|&#8805;/gi, '≥')
    .replace(/&ne;|&#8800;/gi, '≠')
    .replace(/&approx;|&#8776;/gi, '≈')
    .replace(/&alpha;|&#945;/gi, 'α')
    .replace(/&beta;|&#946;/gi, 'β')
    .replace(/&gamma;|&#947;/gi, 'γ')
    .replace(/&Delta;|&#916;/g, 'Δ')
    .replace(/&Omega;|&#937;/g, 'Ω')
    .replace(/&pi;|&#960;/gi, 'π')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&amp;/gi, '&');

  const cleanedLines = working
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/g, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  return normalizeVietnameseUnicodeNFC(cleanedLines || fallbackRawText);
}

/**
 * Normalizes chemical formulas, subscripts, superscripts, ions, physical units,
 * and chemical reaction equations in plain or pasted Word text.
 */
export function formatChemicalAndScientificText(text: string): { text: string; changed: boolean } {
  if (!text) return { text: '', changed: false };
  let current = normalizeVietnameseUnicodeNFC(
    convertHtmlSubSupToUnicode(convertWordOmmlToReadableFormula(text))
  );

  // 0. Unwrap LaTeX math delimiters ($...$, $$...$$, \(...\), \[...\]) & \ce{...}, \text{...} wrappers
  current = current
    .replace(/\$\$([\s\S]*?)\$\$/g, '$1')
    .replace(/\$([^$\n]+)\$/g, '$1')
    .replace(/\\\(([\s\S]*?)\\\)/g, '$1')
    .replace(/\\\[([\s\S]*?)\\\]/g, '$1')
    .replace(/\\ce\{([^{}]+)\}/g, '$1')
    .replace(/\\(?:text|mathrm|mathbf)\{([^{}]+)\}/g, '$1')
    .replace(/\\cdot\b/g, '·')
    .replace(/\\times\b/g, '×')
    .replace(/\\div\b/g, '÷')
    .replace(/\\pm\b/g, '±')
    .replace(/\\(?:le|leq)\b/g, '≤')
    .replace(/\\(?:ge|geq)\b/g, '≥')
    .replace(/\\(?:ne|neq)\b/g, '≠')
    .replace(/\\approx\b/g, '≈')
    .replace(/\\(?:Rightarrow|implies)\b/g, '⇒')
    .replace(/\\(?:Leftrightarrow|iff)\b/g, '⇔')
    .replace(/\\Delta\b/g, 'Δ')
    .replace(/\\Omega\b/g, 'Ω')
    .replace(/\\alpha\b/g, 'α')
    .replace(/\\beta\b/g, 'β')
    .replace(/\\gamma\b/g, 'γ')
    .replace(/\\pi\b/g, 'π')
    .replace(/\\lambda\b/g, 'λ')
    .replace(/\\mu\b/g, 'μ')
    .replace(/\^\{?\\circ\}?/g, '°')
    .replace(/\\(?:sin|cos|tan|cot|log)\b/g, (m) => m.slice(1));

  // 1. Reaction conditions, LaTeX arrows (\xrightarrow, \to, \rightleftharpoons) & Word arrow extenders
  current = current
    // LaTeX \xrightarrow[sub]{sup} and \xrightarrow{cond}
    .replace(/[ \t]*\\xrightarrow\[([^\]]+)\]\s*\{([^{}]+)\}[ \t]*/g, ' → ($2, $1) ')
    .replace(/[ \t]*\\xrightarrow\s*\{([^{}]+)\}[ \t]*/g, ' → ($1) ')
    .replace(/[ \t]*\\xrightleftharpoons\[([^\]]+)\]\s*\{([^{}]+)\}[ \t]*/g, ' ⇄ ($2, $1) ')
    .replace(/[ \t]*\\xrightleftharpoons\s*\{([^{}]+)\}[ \t]*/g, ' ⇄ ($1) ')
    .replace(/[ \t]*\\(?:longrightarrow|rightarrow|to)\b[ \t]*/g, ' → ')
    .replace(/[ \t]*\\(?:rightleftharpoons|leftrightarrow|Longleftrightarrow)\b[ \t]*/g, ' ⇄ ')
    .replace(/\\uparrow\b/g, '↑')
    .replace(/\\downarrow\b/g, '↓')
    // Word inline arrows with parenthesized or bare conditions: --(t°)--> , -(t°, xt)-> , ⎯⎯t°→ , --t°--> , ==t°==>
    .replace(/[ \t]*(?:--|==|[⎯─━―]{1,})\s*\(([^)]+)\)\s*(?:-->|==>|->|[⎯─━―]*\s*(?:→|➔|➜|➞|➡|►|>))[ \t]*/g, ' → ($1) ')
    .replace(/[ \t]*-\s*\(([^)]+)\)\s*->[ \t]*/g, ' → ($1) ')
    .replace(
      /[ \t]*(?:--|==|[⎯─━―]{1,})\s*(t\^?[0o°](?:\s*,\s*(?:xt|p|đpdd|đpnc|as|xúc\s*tác|áp\s*suất))?|đpdd|đpnc|xt|ánh\s*sáng|as|men\s*giấm|lên\s*men)\s*(?:-->|==>|->|[⎯─━―]*\s*(?:→|➔|➜|➞|➡|►|>))[ \t]*/gi,
      ' → ($1) '
    )
    .replace(
      /[ \t]*-\s*(t\^?[0o°](?:\s*,\s*(?:xt|p|đpdd|đpnc|as))?|đpdd|đpnc)\s*->[ \t]*/gi,
      ' → ($1) '
    )
    // Normalize t^o, t^0, t0, to inside reaction condition parentheses
    .replace(/\(\s*t\^?[0o°]\s*(?:,\s*([^)]+))?\)/gi, (_m, extra) =>
      extra ? `(t°, ${extra.trim()})` : '(t°)'
    )
    // Normalize bare "→ t°" or "→(t°)" into " → (t°) "
    .replace(/[ \t]*→[ \t]*\(\s*([^)]+?)\s*\)[ \t]*/g, ' → ($1) ')
    .replace(/[ \t]*⇄[ \t]*\(\s*([^)]+?)\s*\)[ \t]*/g, ' ⇄ ($1) ')
    .replace(/[ \t]*→[ \t]+t(?:°|\^?[0o])\b[ \t]*/gi, ' → (t°) ')
    .replace(/(\d)\s*(?:\^0|\^o)\s*C\b/g, '$1°C')
    .replace(/\b(\d+)\s*oC\b/g, '$1°C');

  // 2. Reversible and forward reaction arrows (avoid touching <= or >= comparisons)
  current = current
    .replace(/[ \t]*(?:<===>|<==>|<=>|<--->|<-->|<->|⇌|⇄)[ \t]*/g, ' ⇄ ')
    .replace(/[ \t]*(?:[⎯─━―]{1,}\s*(?:→|➔|➜|➞|➡|►|>)|───►|──►|===>|==>|--->|-->|->|⟶|➔|➜|➞|➡|→)[ \t]*/g, ' → ');

  // 2b. Repair spaced & underscored chemical formulas from Word/PDF/OCR before gas/precipitate arrows & subscripts
  // e.g. "H_2SO_4" -> "H2SO4", "Al_2(SO_4)_3" -> "Al2(SO4)3", "H 2 SO 4" -> "H2SO4", "2KClO 3" -> "2KClO3", "3O 2^" -> "3O2^"
  current = current
    // Collapse spaces inside & after parenthetical chemical groups: "Al 2 ( SO 4 ) 3" -> "Al2(SO4)3", "Ca ( OH ) 2" -> "Ca(OH)2"
    .replace(
      /(?<![\p{L}])(\d*)([A-Z][a-z]?)(?:[ \t]*(\d+))?[ \t]*\([ \t]*([A-Z][A-Za-z0-9₀-₉ \t]*?)[ \t]*\)[ \t]*([0-9₀-₉n]+)\b/gu,
      (full, coeff: string, metal: string, metalSub: string | undefined, groupInner: string, groupSub: string) => {
        if (!CHEMICAL_ELEMENTS.has(metal)) return full;
        const compactGroup = groupInner.replace(/[ \t]+/g, '');
        const groupEls = compactGroup.match(/[A-Z][a-z]?/g) || [];
        if (groupEls.length === 0 || !groupEls.every((el) => CHEMICAL_ELEMENTS.has(el))) return full;
        return `${coeff}${metal}${metalSub || ''}(${compactGroup})${groupSub}`;
      }
    )
    // Collapse spaces in multi-element or diatomic spaced formulas like "H 2 SO 4", "BaCl 2", "BaSO 4(kết tủa)", "2KClO 3", "3O 2^", "C 6 H 12 O 6"
    .replace(
      /(?<![\p{L}])(\d*)((?:[A-Z][a-z]?)+(?:\d+)?(?:[ \t]+(?:(?:[A-Z][a-z]?)+(?:\d+)?|\d+))+)(?=\^|\s|$|[.,;:!?()[\]{}→⇄+])/gu,
      (full, coeff: string, seq: string) => {
        const collapsed = seq.replace(/[ \t]+/g, '');
        if (!/\d/.test(collapsed)) return full;
        if (NON_CHEMICAL_TOKENS.has(collapsed)) return full;
        const els = collapsed.match(/[A-Z][a-z]?/g) || [];
        if (els.length === 0 || !els.every((el) => CHEMICAL_ELEMENTS.has(el))) return full;
        if (els.length === 1 && !SINGLE_ELEMENT_MOLECULES.has(collapsed)) return full;
        return `${coeff}${collapsed}`;
      }
    )
    // Strip underscores inside pure chemical formulas (e.g. H_2SO_4 -> H2SO4, Ca(OH)_2 -> Ca(OH)2, O_2 -> O2) without touching physics symbols (n_Zn, V_H2)
    .replace(
      /\b((?:[A-Z][a-z]?|\([A-Za-z0-9_]+\))(?:_\{?\d+\}?|[0-9])*){1,}\b/g,
      (full) => {
        if (!full.includes('_')) return full;
        const stripped = full.replace(/_\{?(\d+)\}?/g, '$1');
        const els = stripped.match(/[A-Z][a-z]?/g) || [];
        if (els.length === 0 || !els.every((el) => CHEMICAL_ELEMENTS.has(el))) return full;
        if (els.length === 1 && !SINGLE_ELEMENT_MOLECULES.has(stripped)) return full;
        return stripped;
      }
    );

  // 3. Gas evolution (↑) and Precipitate (↓) arrows after common formulas
  current = current
    .replace(
      /\b(\d*(?:H[2₂]|O[2₂]|N[2₂]|Cl[2₂]|CO[2₂]|SO[2₂]|NH[3₃]|H[2₂]S|NO[2₂]?|CH[4₄]|C[2₂]H[24₂₄]))(?:\^|\s*\(\s*khí\s*\))/gi,
      '$1↑'
    )
    .replace(
      /\b(\d*(?:BaSO[4₄]|AgCl|AgBr|AgI|CaCO[3₃]|BaCO[3₃]|Cu\(OH\)[2₂]|Fe\(OH\)[23₂₃]|Al\(OH\)[3₃]|Mg\(OH\)[2₂]|Zn\(OH\)[2₂]|FeS|CuS|PbS|BaSO[3₃]|CaSO[3₃]))\s*\(\s*(?:kết\s*tủa|r)\s*\)/gi,
      '$1↓'
    );

  // 3b. Electron symbol e- or e^- -> e⁻
  current = current.replace(
    /(?<![\p{L}\p{N}])(\d*e)\^?-(?=\s|$|[.,;:!?)\]}→⇄+])/gu,
    '$1⁻'
  );

  // 4. Explicit caret ion charges: Fe^2+, Fe^{3+}, SO4^2-, SO4^{2-}, PO4^3-, NH4^+, OH^-, H^+
  current = current.replace(
    /\b([A-Za-z0-9₀-₉()]+)\^\{?([1-9][+-]|[+-][1-9]|[+-])\}?(?=\s|$|[.,;:!?)\]}→⇄+])/g,
    (_m, base: string, rawCharge: string) => {
      if (base === '10') return _m; // Preserve 10^n for arithmetic checks
      const normalizedCharge = rawCharge.replace(/^([+-])(\d+)$/, '$2$1');
      return `${base}${toSuperscriptChars(normalizedCharge)}`;
    }
  );

  // 5. Plain-text polyatomic ions with charge (e.g. SO42-, CO32-, SO32-, PO43-, NO3-, HCO3-, NH4+, H3O+, OH-)
  current = current
    .replace(/\bSO42-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'SO₄²⁻')
    .replace(/\bSO32-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'SO₃²⁻')
    .replace(/\bCO32-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'CO₃²⁻')
    .replace(/\bSiO32-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'SiO₃²⁻')
    .replace(/\bCr2O72-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'Cr₂O₇²⁻')
    .replace(/\bCrO42-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'CrO₄²⁻')
    .replace(/\bHPO42-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'HPO₄²⁻')
    .replace(/\bPO43-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'PO₄³⁻')
    .replace(/\bNH4\+(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'NH₄⁺')
    .replace(/\bH3O\+(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'H₃O⁺')
    .replace(/\bNO3-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'NO₃⁻')
    .replace(/\bNO2-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'NO₂⁻')
    .replace(/\bHCO3-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'HCO₃⁻')
    .replace(/\bHSO4-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'HSO₄⁻')
    .replace(/\bHSO3-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'HSO₃⁻')
    .replace(/\bH2PO4-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'H₂PO₄⁻')
    .replace(/\bCH3COO-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'CH₃COO⁻')
    .replace(/\bMnO4-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'MnO₄⁻')
    .replace(/\bClO3-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'ClO₃⁻')
    .replace(/\bAlO2-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'AlO₂⁻')
    .replace(/\b(OH|Cl|Br|I|F|HS|CN)-(?=\s|$|[.,;:!?)\]}→⇄+])/g, '$1⁻')
    .replace(/\bS2-(?=\s|$|[.,;:!?)\]}→⇄+])/g, 'S²⁻');

  // 6. Plain-text monoatomic cations (e.g. Cu2+, Fe2+, Fe3+, Al3+, Ca2+, Mg2+, Ba2+, Zn2+, Ag+, Na+, K+, H+)
  current = current
    .replace(
      /\b(Ca|Mg|Ba|Zn|Cu|Fe|Al|Cr|Pb|Hg|Sn|Ni|Mn|Co|Sr|Au)([23])\+(?=\s|$|[.,;:!?)\]}→⇄+])/g,
      (_m, el: string, digit: string) => `${el}${toSuperscriptChars(`${digit}+`)}`
    )
    .replace(/\b(H|Na|K|Ag|Li)\+(?=\s|$|[.,;:!?)\]}→⇄])/g, '$1⁺');

  // 7. General chemical formulas (multi-element compounds, parenthetical groups like Al2(SO4)3, Ca(OH)2, hydrates, and diatomic molecules)
  current = current.replace(
    /(?<![\p{L}\p{N}\\])(\d*)((?:[A-Z][a-z]?[0-9₀-₉]*|\([A-Za-z0-9₀-₉\-=≡]+\)[0-9₀-₉nₙ]*)+)(?:[ \t]*[·.][ \t]*(\d+|n)[ \t]*(H[2₂]\s*O))?(?![\p{L}\p{N}])/gu,
    (fullMatch, coeff: string, core: string, hydrateCoeff?: string, hydrateWater?: string) => {
      if (!/[0-9]|\)n\b/.test(core) && !hydrateWater) return fullMatch;

      const asciiCore = core.normalize('NFKC');
      if (NON_CHEMICAL_TOKENS.has(asciiCore)) return fullMatch;

      const elementTokens = asciiCore.match(/[A-Z][a-z]?/g) || [];
      if (elementTokens.length === 0) return fullMatch;
      if (!elementTokens.every((el) => CHEMICAL_ELEMENTS.has(el))) return fullMatch;

      const hasParens = /[()]/.test(asciiCore);
      if (elementTokens.length === 1 && !hasParens) {
        if (!SINGLE_ELEMENT_MOLECULES.has(asciiCore)) {
          return fullMatch;
        }
      }

      const formattedCore = core
        .replace(/([A-Z][a-z]?|\))(\d+)/g, (_m, prefix: string, digits: string) => {
          return `${prefix}${toSubscriptDigits(digits)}`;
        })
        .replace(/\)n$/g, ')ₙ');

      const formattedHydrate = hydrateWater
        ? `·${hydrateCoeff || ''}H₂O`
        : '';

      return `${coeff}${formattedCore}${formattedHydrate}`;
    }
  );

  // 8. Physical units with superscripts (m2, cm2, mm2, dm2, km2, m3, cm3, dm3, m/s2)
  current = current
    .replace(/\b(mm|cm|dm|m|km)\^?2\b/g, '$1²')
    .replace(/\b(mm|cm|dm|m|km)\^?3\b/g, '$1³')
    .replace(/\b(m|cm)\/s\^?2\b/g, '$1/s²');

  // 9. Physics indexed symbols (R1, R2, R3, U1, U2, I1, I2) when used as quantities
  current = current.replace(/\b([RUI])([1234])\b/g, (_m, sym: string, digit: string) => {
    return `${sym}${toSubscriptDigits(digit)}`;
  });

  return { text: current, changed: current !== text };
}

