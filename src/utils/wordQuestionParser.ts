export type QuestionValidationStatus =
  | 'valid'
  | 'missing_answer'
  | 'has_explanation'
  | 'needs_review'
  | 'format_error';

export interface ParsedWordQuestion extends Omit<QuizQuestion, 'id'> {
  id: string;
  autoGeneratedExplanation: boolean;
  solutionStatus?: ScientificSolution['status'];
  solutionWarnings?: string[];
  validationStatus?: QuestionValidationStatus;
  hasAnswerMismatch?: boolean;
  inferredAnswerIndex?: number | null;
  hasOleEquationWarning?: boolean;
  detectedAnswerSource:
    | 'explicit_key'
    | 'asterisk'
    | 'formatting'
    | 'answer_table'
    | 'knowledge_inference'
    | 'essay_rubric'
    | 'default_first';
}

export function computeQuestionValidationStatus(q: ParsedWordQuestion): QuestionValidationStatus {
  if (!q.question || q.question.trim().length < 3) {
    return 'format_error';
  }
  if ((q.questionType === 'single_choice' || q.questionType === 'multiple_choice') && (!q.options || q.options.length < 2)) {
    return 'format_error';
  }
  if (q.questionType === 'true_false' && (!q.trueFalseStatements || q.trueFalseStatements.length === 0) && (!q.options || q.options.length < 2)) {
    return 'format_error';
  }
  if (q.hasAnswerMismatch || (q.solutionWarnings && q.solutionWarnings.some(w => /KHÔNG KHỚP|mâu thuẫn/i.test(w)))) {
    return 'needs_review';
  }
  if (q.questionType === 'single_choice' || q.questionType === 'multiple_choice') {
    if (typeof q.correctAnswer !== 'number' || q.correctAnswer < 0 || q.correctAnswer >= (q.options?.length || 0)) {
      return 'missing_answer';
    }
  } else if (q.questionType === 'true_false' && q.trueFalseStatements && q.trueFalseStatements.length > 0) {
    if (q.trueFalseStatements.some(st => st.isTrue === null || st.isTrue === undefined)) {
      return 'missing_answer';
    }
  } else if (q.questionType === 'short_answer') {
    if (!q.shortAnswer || !q.shortAnswer.trim()) {
      return 'missing_answer';
    }
  }
  const hasBlockingWarning = Boolean(
    q.solutionWarnings?.some(
      (w) =>
        !/^Chưa có quy tắc giải đủ tin cậy cho câu này/i.test(w.trim())
    )
  );
  if (q.solutionStatus === 'needs_review' && hasBlockingWarning) {
    return 'needs_review';
  }
  if (
    q.explanation &&
    q.explanation.trim().length > 10 &&
    (q.solutionStatus === 'solved' || q.solutionStatus === 'provided' || q.approvalStatus === 'approved')
  ) {
    return 'has_explanation';
  }
  return 'valid';
}

/** Recompute inferred answers after edits, while retaining explicit teacher keys. */
export function regenerateImportedQuestion(q: ParsedWordQuestion, preserveProvided = false): ParsedWordQuestion {
  const formattedQuestion = formatChemicalAndScientificText(q.question).text;
  const formattedOptions = (q.options || []).map((opt) => formatChemicalAndScientificText(opt).text);
  const formattedExistingExp = q.explanation ? formatChemicalAndScientificText(q.explanation).text : q.explanation;
  const formattedStatements = q.trueFalseStatements?.map((st) => ({
    ...st,
    text: formatChemicalAndScientificText(st.text).text,
    explanation: st.explanation
      ? formatChemicalAndScientificText(st.explanation.replace(/^[a-d]\s*[.)]\s*/i, '')).text
      : st.explanation,
  }));

  const normalizedQ: ParsedWordQuestion = {
    ...q,
    question: formattedQuestion,
    options: formattedOptions,
    trueFalseStatements: formattedStatements,
    explanation: formattedExistingExp || '',
  };

  const keepSource = preserveProvided && !normalizedQ.autoGeneratedExplanation;
  const inferAgain = !keepSource && ['default_first', 'knowledge_inference'].includes(normalizedQ.detectedAnswerSource);
  const solution = generateScientificSolution({
    ...normalizedQ,
    correctAnswer: inferAgain ? -1 : normalizedQ.correctAnswer,
    existingExplanation: keepSource ? normalizedQ.explanation : undefined,
    trueFalseStatements: normalizedQ.trueFalseStatements,
    shortAnswer: normalizedQ.shortAnswer,
    shortAnswerUnit: normalizedQ.shortAnswerUnit,
  });

  const answer =
    normalizedQ.questionType === 'single_choice' || normalizedQ.questionType === 'multiple_choice'
      ? inferAgain
        ? solution.inferredAnswer ?? -1
        : normalizedQ.correctAnswer
      : normalizedQ.correctAnswer;

  const shortAns =
    normalizedQ.questionType === 'short_answer' && (!normalizedQ.shortAnswer || !normalizedQ.shortAnswer.trim()) && solution.inferredNumeric
      ? solution.inferredNumeric.formatted
      : normalizedQ.shortAnswer;

  const shortUnit =
    normalizedQ.questionType === 'short_answer' && (!normalizedQ.shortAnswerUnit || !normalizedQ.shortAnswerUnit.trim()) && solution.inferredNumeric
      ? solution.inferredNumeric.unit
      : normalizedQ.shortAnswerUnit;

  const hasMismatch = Boolean(
    solution.warnings.some((w) => /PHÁT HIỆN ĐÁP ÁN KHÔNG KHỚP|mâu thuẫn/i.test(w))
  );

  const updated: ParsedWordQuestion = {
    ...normalizedQ,
    correctAnswer: answer,
    shortAnswer: shortAns,
    shortAnswerUnit: shortUnit,
    detectedAnswerSource: inferAgain
      ? solution.inferredAnswer === null && !solution.inferredNumeric
        ? 'default_first'
        : 'knowledge_inference'
      : normalizedQ.detectedAnswerSource,
    explanation: solution.explanation,
    solutionSteps: solution.steps,
    solutionStatus: solution.status,
    solutionWarnings: solution.warnings,
    hasAnswerMismatch: hasMismatch,
    inferredAnswerIndex: solution.inferredAnswer,
    sampleAnswer: normalizedQ.questionType === 'essay' ? (normalizedQ.sampleAnswer || solution.steps.join('\n')) : normalizedQ.sampleAnswer,
    autoGeneratedExplanation: !keepSource,
    approvalStatus: normalizedQ.approvalStatus || (keepSource ? 'approved' : 'pending_review'),
  };
  updated.validationStatus = computeQuestionValidationStatus(updated);
  return updated;
}

/**
 * Tạo lời giải ngắn gọn, mạch lạc, chính xác cho nút "AI TẠO LỜI GIẢI" (Quy định mới - Mục 10):
 * - KHÔNG ghi "Bước 1", "Bước 2", "Bước 3", "Bước 4".
 * - KHÔNG ghi "Phân tích dữ kiện", "Dữ kiện đề bài", "Yêu cầu bài toán", "Phương pháp giải".
 * - KHÔNG lặp lại cả 4 phương án A, B, C, D.
 * - Với câu Đúng/Sai: giải thích ngắn gọn trực tiếp cho từng ý a, b, c, d mà không lặp lại ký hiệu a), b), c), d).
 * - Không tự động ghi đè đáp án của giáo viên nếu phát hiện lệch; đánh dấu cảnh báo để giáo viên kiểm tra.
 */
export function generateConciseSolution(q: ParsedWordQuestion): ParsedWordQuestion {
  const base = regenerateImportedQuestion(
    {
      ...q,
      autoGeneratedExplanation: true,
    },
    false
  );

  const norm = normalizeSolutionPresentation((base.solutionSteps || []).join('\n'));
  const conciseSteps = norm.normalizedSteps.length > 0 ? norm.normalizedSteps : base.solutionSteps || [];

  // Đảm bảo dòng kết luận ngắn gọn "Đáp án: ..." ở cuối nếu chưa có
  const hasConclusionLine = conciseSteps.some((line) => /^(?:Đáp án|Chọn đáp án|Đáp số)\b/i.test(line));
  if (!hasConclusionLine) {
    if (base.questionType === 'single_choice' || base.questionType === 'multiple_choice') {
      const chosenIdx =
        typeof base.correctAnswer === 'number' && base.correctAnswer >= 0
          ? base.correctAnswer
          : base.inferredAnswerIndex ?? -1;
      if (chosenIdx >= 0 && base.options[chosenIdx]) {
        conciseSteps.push(`Đáp án: ${String.fromCharCode(65 + chosenIdx)} (${base.options[chosenIdx]}).`);
      }
    } else if (base.questionType === 'short_answer' && base.shortAnswer) {
      conciseSteps.push(
        `Đáp án: ${base.shortAnswer}${base.shortAnswerUnit ? ` ${base.shortAnswerUnit}` : ''}.`
      );
    }
  }

  // Đối với câu Đúng/Sai: cập nhật giải thích ngắn gọn vào từng ý (không lặp lại ký hiệu a), b), c), d))
  let updatedTfStatements = base.trueFalseStatements;
  if (base.questionType === 'true_false' && base.trueFalseStatements?.length) {
    updatedTfStatements = base.trueFalseStatements.map((st) => {
      const inferred = inferTrueFalseStatementScience(st.text);
      const cleanExp = (st.explanation || inferred?.explanation || '')
        .replace(/^[a-d]\s*[.)]\s*/i, '')
        .trim();
      const verdict = st.isTrue === true ? 'Đúng' : st.isTrue === false ? 'Sai' : 'Chưa xác định';
      return {
        ...st,
        explanation:
          cleanExp ||
          `Phát biểu này ${verdict.toLowerCase()} theo kiến thức chuẩn KHTN Lớp ${base.grade}.`,
      };
    });
  }

  const mismatchWarning = base.solutionWarnings?.find((w) =>
    /PHÁT HIỆN ĐÁP ÁN KHÔNG KHỚP|mâu thuẫn/i.test(w)
  );
  const explanationText = [
    ...conciseSteps,
    ...(mismatchWarning && !conciseSteps.some((s) => s.includes(mismatchWarning))
      ? [`⚠️ ${mismatchWarning}`]
      : []),
  ].join('\n');

  const result: ParsedWordQuestion = {
    ...base,
    trueFalseStatements: updatedTfStatements,
    solutionSteps: conciseSteps,
    explanation: explanationText,
    sampleAnswer: base.questionType === 'essay' ? conciseSteps.join('\n') : base.sampleAnswer,
    approvalStatus: 'pending_review',
    autoGeneratedExplanation: true,
  };
  result.validationStatus = computeQuestionValidationStatus(result);
  return result;
}

