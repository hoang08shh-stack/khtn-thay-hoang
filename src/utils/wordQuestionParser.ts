interface GlobalAnswerTables {
  mcqMap: Map<number, number>;
  trueFalseMap: Map<number, Record<string, boolean>>;
  shortAnswerMap: Map<number, { value: string; unit?: string }>;
  explanationMap: Map<number, string>;
}

function parseTrueFalseKeyString(rawKey: string): Record<string, boolean> | null {
  const result: Record<string, boolean> = {};
  // Pattern 1: a-Đ, b-S, c-Đ, d-S or a) Đúng; b) Sai; c) Đúng; d) Sai or a:Đ b:S
  const labeledMatches = [
    ...rawKey.matchAll(/(?:^|[^\p{L}\p{N}])([a-d])\s*[.):\-=\s]\s*(đúng|sai|true|false|đ|s)(?![\p{L}\p{N}])/giu),
  ];
  if (labeledMatches.length >= 2) {
    for (const m of labeledMatches) {
      const label = m[1].toLowerCase();
      const val = m[2].toLowerCase();
      result[label] = val === 'đúng' || val === 'đ' || val === 'true';
    }
    return result;
  }

  // Pattern 2: Đ - S - Đ - S or Đ, S, Đ, S
  const seqMatch = rawKey.match(
    /^\s*(đúng|sai|đ|s)\s*[-,;\/|\s]\s*(đúng|sai|đ|s)\s*[-,;\/|\s]\s*(đúng|sai|đ|s)\s*[-,;\/|\s]\s*(đúng|sai|đ|s)\s*$/iu
  );
  if (seqMatch) {
    const labels = ['a', 'b', 'c', 'd'];
    labels.forEach((lbl, i) => {
      const v = seqMatch[i + 1].toLowerCase();
      result[lbl] = v === 'đúng' || v === 'đ';
    });
    return result;
  }
  return null;
}

/**
 * Extracts global answer & explanation tables at the end of a Word document if present
 * Supports MCQ (1.A 2.B), True/False (Câu 2: a-Đ, b-S, c-Đ, d-S), Short Answer (Câu 3: 2,48), and per-question explanations.
 */
function extractGlobalAnswerAndSolutionTables(text: string): GlobalAnswerTables {
  const mcqMap = new Map<number, number>();
  const trueFalseMap = new Map<number, Record<string, boolean>>();
  const shortAnswerMap = new Map<number, { value: string; unit?: string }>();
  const explanationMap = new Map<number, string>();

  const answerSectionMatch = text.match(
    /\n\s*(?:BẢNG ĐÁP ÁN(?:\s*VÀ\s*HƯỚNG\s*DẪN\s*GIẢI)?|ĐÁP ÁN THAM KHẢO|ĐÁP ÁN VÀ HƯỚNG DẪN GIẢI|ĐÁP ÁN CHI TIẾT|HƯỚNG DẪN GIẢI CHI TIẾT)(?![\p{L}\p{N}])([\s\S]*)$/iu
  );
  const targetZone = answerSectionMatch ? answerSectionMatch[1] : '';
  if (!targetZone) {
    return { mcqMap, trueFalseMap, shortAnswerMap, explanationMap };
  }

  // 1. Parse line by line for structured keys (True/False, Short Answer, Explanations)
  const zoneLines = targetZone.split('\n').map((l) => l.trim()).filter(Boolean);
  let activeExpQNum: number | null = null;
  const activeExpLines: Map<number, string[]> = new Map();

  for (const line of zoneLines) {
    // Check if line starts with "Câu X:" or "Lời giải Câu X:" or "Bài X:"
    const qLineMatch = line.match(
      /^(?:(?:Lời\s*giải|Giải\s*thích|Hướng\s*dẫn(?:\s*giải)?|HDG)\s*)?(?:Câu|Bài|Question)\s*(\d{1,3})\s*[:.)-]?\s*(.*)$/i
    );
    if (qLineMatch) {
      const qNum = parseInt(qLineMatch[1], 10);
      const rest = qLineMatch[2].trim();
      activeExpQNum = qNum;

      // Check True/False key in rest
      const tfParsed = parseTrueFalseKeyString(rest);
      if (tfParsed) {
        trueFalseMap.set(qNum, tfParsed);
        continue;
      }

      // Check single MCQ letter: "A" or "A. Vì..." or "Chọn A"
      const singleMcq = rest.match(/^(?:Chọn\s+|Đáp\s*án\s*)?\*?([A-D])\b(?:\s*[.:=-]\s*(.*))?$/i);
      if (singleMcq) {
        mcqMap.set(qNum, singleMcq[1].toUpperCase().charCodeAt(0) - 65);
        if (singleMcq[2]?.trim()) {
          activeExpLines.set(qNum, [singleMcq[2].trim()]);
        }
        continue;
      }

      // Check short numeric answer: "2,48" or "2,479 L" or "-12,5"
      const shortMatch = rest.match(/^(?:Đáp\s*án\s*[:=-]?\s*|Đáp\s*số\s*[:=-]?\s*)?([-+]?\d+(?:[.,]\d+)?)\s*([\p{L}Ω°%/²³₀-₉]+)?(?:\s*[.;|-]\s*(?:Lời\s*giải\s*[:=-]?\s*)?(.*))?$/iu);
      if (shortMatch) {
        shortAnswerMap.set(qNum, {
          value: shortMatch[1],
          unit: shortMatch[2]?.trim() || undefined,
        });
        if (shortMatch[3]?.trim()) {
          activeExpLines.set(qNum, [shortMatch[3].trim()]);
        }
        continue;
      }

      // Otherwise treat rest as explanation for qNum
      if (rest) {
        const cleanedExp = rest.replace(/^(?:Lời\s*giải|Giải\s*thích|HDG)\s*[:=-]?\s*/i, '').trim();
        if (cleanedExp) {
          activeExpLines.set(qNum, [...(activeExpLines.get(qNum) || []), cleanedExp]);
        }
      }
      continue;
    }

    if (activeExpQNum !== null && !/^(?:PHẦN\s+[I1234V]+|BẢNG\s+ĐÁP\s+ÁN)/i.test(line)) {
      // Check if line is compact MCQ pairs like "1.A  2.B  3.C"
      const compactPairs = [...line.matchAll(/(?:^|\s)(?:Câu\s*)?(\d{1,3})\s*[.:\-)]\s*([A-D])(?=\s|$|[,;])/gi)];
      if (compactPairs.length >= 2) {
        for (const cp of compactPairs) {
          mcqMap.set(parseInt(cp[1], 10), cp[2].toUpperCase().charCodeAt(0) - 65);
        }
        activeExpQNum = null;
        continue;
      }
      activeExpLines.set(activeExpQNum, [...(activeExpLines.get(activeExpQNum) || []), line]);
    }
  }

  for (const [qNum, expArr] of activeExpLines.entries()) {
    if (expArr.length > 0) {
      explanationMap.set(qNum, expArr.join('\n'));
    }
  }

  // 2. Also scan compact MCQ pairs anywhere in targetZone (e.g. "1.A  2.B  3.C  4.D" or "1-A, 2-B")
  const pairRegex = /(?:^|[\s,;|\t])(?:Câu\s*)?(\d{1,3})\s*[.:\-)]\s*([A-D])\b/gi;
  let match: RegExpExecArray | null;
  while ((match = pairRegex.exec(targetZone)) !== null) {
    const qNum = parseInt(match[1], 10);
    const ansChar = match[2].toUpperCase();
    const ansIdx = ansChar.charCodeAt(0) - 65;
    if (qNum > 0 && ansIdx >= 0 && ansIdx <= 3 && !mcqMap.has(qNum) && !trueFalseMap.has(qNum)) {
      mcqMap.set(qNum, ansIdx);
    }
  }

  // 3. Scan compact Short Answer pairs like "1. 2,48 | 2. 0,5" when not matched as MCQ
  const shortPairRegex = /(?:^|[\s,;|\t])(?:Câu\s*)?(\d{1,3})\s*[.:\-)]\s*([-+]?\d+(?:[.,]\d+)?)\s*(?=$|[\s,;|])/gi;
  let sm: RegExpExecArray | null;
  while ((sm = shortPairRegex.exec(targetZone)) !== null) {
    const qNum = parseInt(sm[1], 10);
    if (qNum > 0 && !mcqMap.has(qNum) && !trueFalseMap.has(qNum) && !shortAnswerMap.has(qNum)) {
      shortAnswerMap.set(qNum, { value: sm[2] });
    }
  }

  return { mcqMap, trueFalseMap, shortAnswerMap, explanationMap };
}

/**
 * Extracts bold/underlined option markers from HTML converted by mammoth
 */
function extractFormattedCorrectOptionMap(html?: string): Map<number, number> {
  const map = new Map<number, number>();
  if (!html) return map;

  const blocks = html.split(/(?=(?:Câu|Bài|Question)\s+\d+)/i);
  blocks.forEach((block, idx) => {
    const qNumMatch = block.match(/(?:Câu|Bài|Question)\s+(\d+)/i);
    const qNum = qNumMatch ? parseInt(qNumMatch[1], 10) : idx + 1;

    const formattedOptMatch = block.match(/<(?:strong|b|u|em|mark)[^>]*>\s*\*?\s*([A-D])\s*[.)]/i);
    if (formattedOptMatch) {
      const letter = formattedOptMatch[1].toUpperCase();
      map.set(qNum, letter.charCodeAt(0) - 65);
    }
  });

  return map;
}

/**
 * Evaluates well-known KHTN statements for True/False inference ONLY when clearly supported by scientific facts.
 * Returns null if the statement is not a deterministic fact so the teacher is prompted to verify.
 */
function inferTrueFalseStatementScience(text: string): { isTrue: boolean; explanation: string } | null {
  const s = text.trim();
  if (/kim loại.*dẫn điện|dẫn điện.*kim loại/i.test(s) && !/không/i.test(s)) {
    return { isTrue: true, explanation: 'Kim loại có các electron tự do trong mạng tinh thể nên có khả năng dẫn điện tốt.' };
  }
  if (/tất cả.*kim loại.*phản ứng với nước|mọi kim loại.*tác dụng với nước/i.test(s)) {
    return { isTrue: false, explanation: 'Chỉ các kim loại kiềm và một số kim loại kiềm thổ (Na, K, Ca, Ba) mới phản ứng mạnh với nước ở nhiệt độ thường; các kim loại như Cu, Ag, Au, Fe không phản ứng với nước ở nhiệt độ thường.' };
  }
  if (/kim loại.*nhường electron|nhường electron.*ion dương/i.test(s) && !/không/i.test(s)) {
    return { isTrue: true, explanation: 'Trong các phản ứng hóa học, nguyên tử kim loại có xu hướng nhường electron lớp ngoài cùng để tạo thành ion dương (cation).' };
  }
  if (/(?:đồng|\bCu\b).*phản ứng.*(?:HCl|H2SO4\s*loãng|H₂SO₄\s*loãng).*giải phóng.*(?:H2|H₂|khí)/i.test(s) && !/không/i.test(s)) {
    return { isTrue: false, explanation: 'Đồng (Cu) đứng sau Hydrogen trong dãy hoạt động hóa học nên không phản ứng với dung dịch HCl loãng hoặc H₂SO₄ loãng.' };
  }
  if (/(?:kẽm|\bZn\b|sắt|\bFe\b|magie|\bMg\b|nhôm|\bAl\b).*(?:phản ứng|tác dụng).*(?:HCl|H2SO4\s*loãng|H₂SO₄\s*loãng).*giải phóng.*(?:H2|H₂)/i.test(s) && !/không/i.test(s)) {
    return { isTrue: true, explanation: 'Kim loại đứng trước H trong dãy hoạt động hóa học (Mg, Al, Zn, Fe) tác dụng với dung dịch acid loãng giải phóng khí H₂.' };
  }
  if (/quỳ tím.*hóa đỏ.*(?:acid|axit|HCl|H2SO4|H₂SO₄)/i.test(s) || /(?:acid|axit|HCl|H2SO4|H₂SO₄).*quỳ tím.*hóa đỏ/i.test(s)) {
    return { isTrue: true, explanation: 'Dung dịch acid phân li ra ion H⁺ làm giấy quỳ tím chuyển sang màu đỏ.' };
  }
  if (/phenolphthalein.*hóa hồng.*(?:NaOH|KOH|Ca\(OH\)2|Ca\(OH\)₂|kiềm|base)/i.test(s) || /(?:NaOH|KOH|Ca\(OH\)2|Ca\(OH\)₂|kiềm|base).*phenolphthalein.*màu hồng/i.test(s)) {
    return { isTrue: true, explanation: 'Dung dịch base tan (kiềm) có pH > 7 làm phenolphthalein chuyển sang màu hồng.' };
  }
  return null;
}

/**
 * Extracts MCQ options A, B, C, D from a question block, supporting:
 * - Multi-line options (A. ... \n B. ... \n C. ... \n D. ...)
 * - Single-line inline options (A. Cu B. Ag C. Zn D. Au)
 * - Parenthesis options (A) ... B) ... C) ... D) ...)
 */
function extractMcqOptionsFromBlock(textForOptions: string): Array<{
  letter: string;
  starred: boolean;
  matchStart: number;
  contentStart: number;
}> {
  const optionRegex = /(?:^|\n|\s+|\t)(\*?)\s*([A-D])(\*?)\s*[.:)]\s+/g;
  const candidates: Array<{
    letter: string;
    starred: boolean;
    matchStart: number;
    contentStart: number;
  }> = [];

  let m: RegExpExecArray | null;
  while ((m = optionRegex.exec(textForOptions)) !== null) {
    const fullMatch = m[0];
    const leadingOffset = fullMatch.search(/\*?\s*[A-D]\*?\s*[.:)]/);
    const actualStart = m.index + (leadingOffset >= 0 ? leadingOffset : 0);
    const letter = m[2].toUpperCase();
    const starred = m[1] === '*' || m[3] === '*';
    candidates.push({
      letter,
      starred,
      matchStart: actualStart,
      contentStart: m.index + fullMatch.length,
    });
  }

  // Filter sequential A -> B -> (C) -> (D) starting from the last valid 'A' before 'B'
  const aIndices = candidates.map((c, idx) => (c.letter === 'A' ? idx : -1)).filter((i) => i >= 0);
  for (const startIdx of aIndices) {
    const seq: typeof candidates = [candidates[startIdx]];
    const expectedLetters = ['B', 'C', 'D'];
    let expPtr = 0;
    for (let j = startIdx + 1; j < candidates.length && expPtr < expectedLetters.length; j++) {
      if (candidates[j].letter === expectedLetters[expPtr]) {
        seq.push(candidates[j]);
        expPtr++;
      }
    }
    if (seq.length >= 2 && seq[0].letter === 'A' && seq[1].letter === 'B') {
      return seq;
    }
  }
  return [];
}

/**
 * Extracts True/False sub-statements a), b), c), d) or a., b., c., d.
 */
function extractTrueFalseStatementsFromBlock(
  textForOptions: string,
  qId: string,
  questionLevelTfKey: Record<string, boolean> | null,
  normalizer: (t: string) => { text: string; changed: boolean }
): {
  stem: string;
  statements: TrueFalseStatement[];
  hasInlineKeys: boolean;
} | null {
  const stmtRegex = /(?:^|\n|\s{2,}|\t)(\*?)\s*([a-d])(\*?)\s*[.)]\s+/g;
  const candidates: Array<{
    label: 'a' | 'b' | 'c' | 'd';
    starred: boolean;
    matchStart: number;
    contentStart: number;
  }> = [];

  let m: RegExpExecArray | null;
  while ((m = stmtRegex.exec(textForOptions)) !== null) {
    const fullMatch = m[0];
    const leadingOffset = fullMatch.search(/\*?\s*[a-d]\*?\s*[.)]/);
    const actualStart = m.index + (leadingOffset >= 0 ? leadingOffset : 0);
    const label = m[2].toLowerCase() as 'a' | 'b' | 'c' | 'd';
    const starred = m[1] === '*' || m[3] === '*';
    candidates.push({
      label,
      starred,
      matchStart: actualStart,
      contentStart: m.index + fullMatch.length,
    });
  }

  // Find sequence starting at 'a' -> 'b' -> 'c' -> ('d')
  const aIndices = candidates.map((c, idx) => (c.label === 'a' ? idx : -1)).filter((i) => i >= 0);
  let seq: typeof candidates = [];
  for (const startIdx of aIndices) {
    const currentSeq: typeof candidates = [candidates[startIdx]];
    const expected = ['b', 'c', 'd'] as const;
    let expPtr = 0;
    for (let j = startIdx + 1; j < candidates.length && expPtr < expected.length; j++) {
      if (candidates[j].label === expected[expPtr]) {
        currentSeq.push(candidates[j]);
        expPtr++;
      }
    }
    if (currentSeq.length >= 2 && currentSeq[0].label === 'a' && currentSeq[1].label === 'b') {
      seq = currentSeq;
      break;
    }
  }

  if (seq.length < 2) return null;

  const stem = textForOptions.slice(0, seq[0].matchStart).trim();
  const anyStarred = seq.some((s) => s.starred);
  let hasInlineKeys = anyStarred;

  const statements: TrueFalseStatement[] = seq.map((item, i) => {
    const nextStart = i + 1 < seq.length ? seq[i + 1].matchStart : textForOptions.length;
    let rawStmt = textForOptions.slice(item.contentStart, nextStart).trim();

    // Check inline Đúng/Sai marker at the end of the statement: "(Đúng)", "(Sai)", "(Đ)", "(S)", "[Đ]", "[S]", "-> Đúng", "-> Sai"
    let inlineBool: boolean | null = null;
    const inlineMatch = rawStmt.match(
      /(?:\(\s*(đúng|sai|true|false|đ|s)\s*\)|\[\s*(đúng|sai|true|false|đ|s)\s*\]|(?:→|->|—|-|:)\s*(đúng|sai|true|false))\s*[.;]?\s*$/iu
    );
    if (inlineMatch) {
      const token = (inlineMatch[1] || inlineMatch[2] || inlineMatch[3]).toLowerCase();
      inlineBool = token === 'đúng' || token === 'đ' || token === 'true';
      rawStmt = rawStmt.slice(0, inlineMatch.index).trim();
      hasInlineKeys = true;
    } else if (anyStarred) {
      inlineBool = item.starred;
    }

    const normText = normalizer(rawStmt).text;
    let finalBool: boolean | null = inlineBool;
    if (finalBool === null && questionLevelTfKey && item.label in questionLevelTfKey) {
      finalBool = questionLevelTfKey[item.label];
    }

    let stmtExp: string | undefined;
    const inferredFact = inferTrueFalseStatementScience(normText);
    if (finalBool === null && inferredFact) {
      finalBool = inferredFact.isTrue;
      stmtExp = inferredFact.explanation;
    } else if (inferredFact && inferredFact.isTrue === finalBool) {
      stmtExp = inferredFact.explanation;
    }

    return {
      id: `${qId}_tf_${item.label}`,
      label: item.label,
      text: normText,
      isTrue: finalBool,
      explanation: stmtExp,
    };
  });

  return { stem, statements, hasInlineKeys };
}

/**
 * Main parser: Converts raw Word text (and optional HTML) into web QuizQuestion format
 * Supporting all 4 GDPT 2018 question types:
 * 1. Trắc nghiệm nhiều lựa chọn (single_choice / multiple_choice)
 * 2. Trắc nghiệm Đúng/Sai 4 ý a, b, c, d (true_false)
 * 3. Trắc nghiệm Trả lời ngắn (short_answer)
 * 4. Tự luận (essay)
 */
export function parseWordContentToQuestions(
  rawText: string,
  options: WordParseOptions = {}
): ParsedWordQuestionResult {
  const {
    htmlContent,
    defaultGrade = 8,
    defaultDomain = 'hoa-hoc',
    defaultLessonId,
    autoStandardizeIupac = true,
    sourceDocumentName,
  } = options;

  const warnings: string[] = [];
  if ((!rawText || !rawText.trim()) && (!htmlContent || !htmlContent.trim())) {
    return {
      questions: [],
      warnings: ['Nội dung tệp Word trống hoặc không có văn bản câu hỏi.'],
      stats: {
        totalParsed: 0,
        autoExplainedCount: 0,
        iupacNormalizedCount: 0,
        essayCount: 0,
        trueFalseCount: 0,
        shortAnswerCount: 0,
        mcqCount: 0,
      },
    };
  }

  // Detect legacy MathType / OLE equation objects and emit a clear warning
  const oleCheck = detectLegacyOleEquations(`${rawText || ''}\n${htmlContent || ''}`);
  if (oleCheck.hasOleEquation) {
    warnings.push(
      `Phát hiện ${oleCheck.count} công thức dạng đối tượng cũ (MathType/OLE). Hệ thống đã giữ nguyên hình ảnh và đánh dấu để giáo viên kiểm tra.`
    );
  }

  // Automatically convert legacy Vietnamese encodings (TCVN3, VNI-Windows, UTF-8 Mojibake, NFD, detached accents)
  const encodingInfo = detectLegacyVietnameseEncoding(rawText || '', htmlContent || '');
  const cleanRawText = convertLegacyVietnameseToUnicode(
    rawText || '',
    encodingInfo.hasLegacyFontIssue ? encodingInfo.detectedEncoding : undefined
  );
  const cleanHtmlContent = htmlContent
    ? convertLegacyVietnameseToUnicode(
        htmlContent,
        encodingInfo.hasLegacyFontIssue ? encodingInfo.detectedEncoding : undefined
      )
    : undefined;

  // Always prefer Mammoth HTML if it contains sub/sup, images, tables, or OMML equations
  const shouldUseHtml =
    Boolean(cleanHtmlContent && cleanHtmlContent.trim()) &&
    (/<(?:sub|sup|img|table|m:oMath)\b/i.test(cleanHtmlContent!) || !cleanRawText.trim());

  const sourceText = shouldUseHtml
    ? extractFormattedTextFromMammothHtml(cleanHtmlContent!, cleanRawText)
    : /<(?:sub|sup|img|table|m:oMath)\b/i.test(cleanRawText)
    ? extractFormattedTextFromMammothHtml(cleanRawText, cleanRawText)
    : normalizeVietnameseUnicodeNFC(
        convertHtmlSubSupToUnicode(convertWordOmmlToReadableFormula(cleanRawText))
      );

  const normalizedText = sourceText.replace(/\r\n/g, '\n').replace(/\r/g, '\n');

  // 1. Extract global answer & explanation tables if placed at the bottom of the document
  const globalTables = extractGlobalAnswerAndSolutionTables(normalizedText);
  const htmlFormattedMap = extractFormattedCorrectOptionMap(htmlContent);

  const bodyWithoutAnswerTable = normalizedText.replace(
    /\n\s*(?:BẢNG ĐÁP ÁN|ĐÁP ÁN THAM KHẢO|ĐÁP ÁN VÀ HƯỚNG DẪN GIẢI|ĐÁP ÁN CHI TIẾT|HƯỚNG DẪN GIẢI CHI TIẾT)\b[\s\S]*$/i,
    ''
  );

  // 2. Split into question blocks while tracking current section type
  type SectionMode = 'mcq' | 'true_false' | 'short_answer' | 'essay';
  const lines = bodyWithoutAnswerTable.split('\n');
  const questionBlocks: Array<{
    qNumber: number;
    headerLine: string;
    bodyLines: string[];
    sectionMode: SectionMode;
    explicitTagMode: SectionMode | null;
    rawSourceText: string;
  }> = [];

  const questionStartRegex =
    /^\s*(?:(?:Câu|Bài|Question)\s*(\d+)\s*(\([^)]*\)|\[[^\]]*\])?\s*[:.)-]?\s*|(\d+)\s*[.)]\s+)(.*)$/i;

  let currentBlock: {
    qNumber: number;
    headerLine: string;
    bodyLines: string[];
    sectionMode: SectionMode;
    explicitTagMode: SectionMode | null;
    rawLines: string[];
  } | null = null;
  let currentSectionMode: SectionMode = 'mcq';

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;

    // Detect section headers
    if (/^(?:PHẦN\s*(?:I|II|III|IV|1|2|3|4|A|B|C|D)\b|[I1234V]+\.|[A-D]\.)?\s*[:.-]?\s*(?:TRẮC\s*NGHIỆM\s*)?ĐÚNG\s*[/\-]?\s*SAI\b/i.test(line)) {
      currentSectionMode = 'true_false';
      continue;
    }
    if (/^(?:PHẦN\s*(?:I|II|III|IV|1|2|3|4|A|B|C|D)\b|[I1234V]+\.|[A-D]\.)?\s*[:.-]?\s*(?:TRẮC\s*NGHIỆM\s*)?TRẢ\s*LỜI\s*NGẮN\b/i.test(line)) {
      currentSectionMode = 'short_answer';
      continue;
    }
    if (/^(?:PHẦN\s*(?:I|II|III|IV|1|2|3|4|A|B|C|D)\b|[I1234V]+\.|[A-D]\.)\s*[:.-]?\s*TỰ\s*LUẬN|^TỰ\s*LUẬN\b/i.test(line)) {
      currentSectionMode = 'essay';
      continue;
    }
    if (/^(?:PHẦN\s*(?:I|1|A)\b|I\.|A\.)\s*[:.-]?\s*TRẮC\s*NGHIỆM/i.test(line)) {
      currentSectionMode = 'mcq';
      continue;
    }

    // Skip common exam header titles before Question 1
    if (
      !currentBlock &&
      /^(?:ĐỀ KIỂM TRA|TRƯỜNG THCS|MÔN:\s*KHOA HỌC TỰ NHIÊN|THỜI GIAN LÀM BÀI|HỌ VÀ TÊN)/i.test(
        line
      )
    ) {
      continue;
    }

    const startMatch = line.match(questionStartRegex);
    const looksLikeStepLine = /^(?:[-•+]\s*)?Bước\s*\d+/i.test(line);
    // Avoid treating a bare "1. ..." line inside an explanation or rubric as a new question if the previous header used "Câu X"
    const isBareNumberHeader = Boolean(startMatch && !startMatch[1] && startMatch[3]);
    const insideExplanationOrRubric =
      currentBlock &&
      currentBlock.bodyLines.some((bl) =>
        /^(?:Lời\s*giải|Giải\s*thích|Hướng\s*dẫn|Biểu\s*điểm|Thang\s*điểm)/i.test(bl)
      );

    if (startMatch && !looksLikeStepLine && !(isBareNumberHeader && insideExplanationOrRubric)) {
      const numStr = startMatch[1] || startMatch[3];
      const tagStr = startMatch[2] || '';
      const qNum = parseInt(numStr, 10);
      const remainder = startMatch[4] || '';
      if (currentBlock) {
        questionBlocks.push({
          ...currentBlock,
          rawSourceText: currentBlock.rawLines.join('\n'),
        });
      }

      let explicitTagMode: SectionMode | null = null;
      const combinedTag = `${tagStr} ${remainder}`;
      if (/tự\s*luận|essay/i.test(combinedTag)) {
        explicitTagMode = 'essay';
      } else if (/đúng\s*[/\-]?\s*sai|true\s*[/\-]?\s*false/i.test(combinedTag)) {
        explicitTagMode = 'true_false';
      } else if (/trả\s*lời\s*ngắn|short\s*answer/i.test(combinedTag)) {
        explicitTagMode = 'short_answer';
      }

      const cleanedHeader = remainder
        .replace(/^\s*\(?(?:tự\s*luận|đúng\s*[/\-]?\s*sai|trả\s*lời\s*ngắn)\)?\s*[:.-]?\s*/i, '')
        .trim();

      currentBlock = {
        qNumber: qNum || questionBlocks.length + 1,
        headerLine: cleanedHeader,
        bodyLines: [],
        sectionMode: currentSectionMode,
        explicitTagMode,
        rawLines: [rawLine],
      };
    } else if (currentBlock) {
      currentBlock.bodyLines.push(line);
      currentBlock.rawLines.push(rawLine);
    }
  }
  if (currentBlock) {
    questionBlocks.push({
      ...currentBlock,
      rawSourceText: currentBlock.rawLines.join('\n'),
    });
  }

  // Fallback if no numbered headers found
  if (questionBlocks.length === 0 && bodyWithoutAnswerTable.trim()) {
    const nonEmptyLines = lines.map((l) => l.trim()).filter(Boolean);
    if (nonEmptyLines.length > 0) {
      questionBlocks.push({
        qNumber: 1,
        headerLine: nonEmptyLines[0],
        bodyLines: nonEmptyLines.slice(1),
        sectionMode: currentSectionMode,
        explicitTagMode: null,
        rawSourceText: nonEmptyLines.join('\n'),
      });
    }
  }

  const parsedQuestions: ParsedWordQuestion[] = [];
  let autoExplainedCount = 0;
  let iupacNormalizedCount = 0;
  let essayCount = 0;
  let trueFalseCount = 0;
  let shortAnswerCount = 0;
  let mcqCount = 0;

  questionBlocks.forEach((block, idx) => {
    const qId = `q-word-${Date.now()}-${idx + 1}`;
    const fullBlockLines = [block.headerLine, ...block.bodyLines].filter(Boolean);

    // Extract [IMG:...] and [TABLE:...] tokens from this question block
    const questionImages: string[] = [];
    const questionTables: string[] = [];

    let explicitCorrectIndex: number | null = null;
    let explicitMultipleIndices: number[] | null = null;
    let explicitTrueFalseKey: Record<string, boolean> | null =
      globalTables.trueFalseMap.get(block.qNumber) || null;
    let explicitShortAnswer: { value: string; unit?: string } | null =
      globalTables.shortAnswerMap.get(block.qNumber) || null;

    let detectedSource: ParsedWordQuestion['detectedAnswerSource'] =
      explicitTrueFalseKey || explicitShortAnswer ? 'answer_table' : 'default_first';

    const explanationLines: string[] = [];
    const rubricLines: string[] = [];
    let extractedHint = '';
    let isCollectingExplanation = false;
    let isCollectingRubric = false;

    const cleanLines: string[] = [];
    for (const rawLine of fullBlockLines) {
      // Extract image tokens
      let line = rawLine.replace(/\[IMG:([^\]]+)\]/g, (_m, src: string) => {
        if (src && !questionImages.includes(src)) {
          questionImages.push(src);
        }
        return '';
      });
      // Extract table tokens
      line = line.replace(/\[TABLE:([^\]]+)\]/g, (_m, encoded: string) => {
        try {
          const decoded = decodeURIComponent(encoded);
          if (decoded && !questionTables.includes(decoded)) {
            questionTables.push(decoded);
          }
        } catch {
          // ignore malformed URI
        }
        return '';
      });
      line = line.trim();
      if (!line) continue;

      // 1. Check for True/False answer line: "Đáp án: a-Đ, b-S, c-Đ, d-S" or "Đáp án: Đ - S - Đ - S"
      const tfAnsLineMatch = line.match(
        /^(?:Đáp\s*án(?:\s*đúng\/sai)?|ĐA|Key|Answer)\s*[:=-]?\s*(.+)$/i
      );
      if (tfAnsLineMatch) {
        const tfKeyCandidate = parseTrueFalseKeyString(tfAnsLineMatch[1].trim());
        if (tfKeyCandidate) {
          explicitTrueFalseKey = tfKeyCandidate;
          detectedSource = 'explicit_key';
          continue;
        }
      }

      // 2. Check for Multiple Choice answer line: "Đáp án: C" or "Đáp án: A, C"
      const mcqMultiMatch = line.match(
        /^(?:Đáp\s*án(?:\s*đúng)?|ĐA|Chọn(?:\s*đáp\s*án)?|Key|Answer)\s*[:=-]?\s*\*?([A-D](?:\s*[,;]\s*[A-D])+)\b(.*)$/i
      );
      if (mcqMultiMatch) {
        const letters = mcqMultiMatch[1]
          .split(/[,;]/)
          .map((s) => s.trim().toUpperCase())
          .filter((s) => /^[A-D]$/.test(s));
        if (letters.length > 0) {
          explicitMultipleIndices = letters.map((l) => l.charCodeAt(0) - 65);
          explicitCorrectIndex = explicitMultipleIndices[0];
          detectedSource = 'explicit_key';
          continue;
        }
      }

      const ansMatch = line.match(
        /^(?:Đáp\s*án(?:\s*đúng)?|ĐA|Chọn(?:\s*đáp\s*án)?|Key|Answer)\s*[:=-]?\s*\*?([A-D])\b(.*)$/i
      );
      if (ansMatch) {
        explicitCorrectIndex = ansMatch[1].toUpperCase().charCodeAt(0) - 65;
        detectedSource = 'explicit_key';
        const trailingExp = ansMatch[2]?.replace(/^[\s.,;-]+/, '').trim();
        if (trailingExp && trailingExp.length > 5) {
          explanationLines.push(trailingExp);
        }
        continue;
      }

      // 3. Check for Short Answer key line: "Đáp án: 2,479" or "Đáp số: 2,48 L" or "Đáp án: 1,25 lít"
      const shortAnsMatch = line.match(
        /^(?:Đáp\s*án(?:\s*trả\s*lời\s*ngắn)?|Đáp\s*số|Kết\s*quả|ĐA|Key|Answer)\s*[:=-]?\s*([-+]?\d+(?:[.,]\d+)?)\s*([\p{L}Ω°%/²³₀-₉]+)?\s*$/iu
      );
      if (shortAnsMatch) {
        explicitShortAnswer = {
          value: shortAnsMatch[1],
          unit: shortAnsMatch[2]?.trim() || undefined,
        };
        detectedSource = 'explicit_key';
        continue;
      }

      // 4. Check for Rubric / Biểu điểm line
      const rubricMatch = line.match(/^(?:Biểu\s*điểm|Thang\s*điểm|Tiêu\s*chí\s*chấm)\s*[:=-]?\s*(.*)$/i);
      if (rubricMatch) {
        isCollectingRubric = true;
        isCollectingExplanation = false;
        if (rubricMatch[1]?.trim()) {
          rubricLines.push(rubricMatch[1].trim());
        }
        continue;
      }

      // 5. Check for Explanation / Lời giải line
      const expMatch = line.match(
        /^(?:Lời\s*giải(?:\s*chi\s*tiết)?|Giải\s*thích(?:\s*chi\s*tiết)?|Hướng\s*dẫn(?:\s*giải)?|Đáp\s*án\s*tự\s*luận|HDG|Explanation)\s*[:=-]?\s*(.*)$/i
      );
      if (expMatch) {
        isCollectingExplanation = true;
        isCollectingRubric = false;
        if (expMatch[1]?.trim()) {
          explanationLines.push(expMatch[1].trim());
        }
        continue;
      }

      const hintMatch = line.match(/^(?:Gợi\s*ý|Hint)\s*[:=-]?\s*(.+)$/i);
      if (hintMatch) {
        extractedHint = hintMatch[1].trim();
        continue;
      }

      if (isCollectingRubric) {
        rubricLines.push(line);
        continue;
      }

      if (isCollectingExplanation) {
        explanationLines.push(line.replace(/^[-•+*]\s*/, '').trim());
        continue;
      }

      cleanLines.push(line);
    }

    // Merge True/False key, Short Answer key, and Explanation from end-of-file table if not already present inline
    if (!explicitTrueFalseKey && globalTables.trueFalseMap.has(block.qNumber)) {
      explicitTrueFalseKey = globalTables.trueFalseMap.get(block.qNumber)!;
      detectedSource = 'answer_table';
    }
    if (!explicitShortAnswer && globalTables.shortAnswerMap.has(block.qNumber)) {
      explicitShortAnswer = globalTables.shortAnswerMap.get(block.qNumber)!;
      detectedSource = 'answer_table';
    }
    if (explanationLines.length === 0 && globalTables.explanationMap.has(block.qNumber)) {
      explanationLines.push(globalTables.explanationMap.get(block.qNumber)!);
    }

    let extractedExplanation = explanationLines.join('\n').trim();
    const extractedRubric = rubricLines.join('\n').trim();
    const textForOptions = cleanLines.join('\n');

    const normalizer = autoStandardizeIupac
      ? normalizeChemicalNomenclature
      : formatChemicalAndScientificText;

    // Step A: Try MCQ option extraction (A, B, C, D)
    const mcqMatches = extractMcqOptionsFromBlock(textForOptions);

    // Step B: Try True/False statement extraction (a, b, c, d)
    const tfExtracted =
      mcqMatches.length < 2
        ? extractTrueFalseStatementsFromBlock(textForOptions, qId, explicitTrueFalseKey, normalizer)
        : null;

    // Determine whether tfExtracted is genuinely a True/False question vs an Essay with sub-questions (like Câu 5 in SAMPLE_WORD_QUIZ_TEXT)
    const isEssayImperativeSubparts =
      tfExtracted &&
      tfExtracted.statements.some((st) =>
        /^(?:Viết\s+phương\s+trình|Hãy\s+tính|Tính\s+thể\s+tích|Tính\s+nồng\s+độ|Tính\s+khối\s+lượng|Trình\s+bày|Giải\s+thích\s+hiện\s+tượng|Nêu\s+hiện\s+tượng|Vẽ\s+sơ\s+đồ)/i.test(
          st.text.trim()
        )
      );

    const isGenuineTrueFalse =
      Boolean(tfExtracted) &&
      block.explicitTagMode !== 'essay' &&
      block.sectionMode !== 'essay' &&
      (block.sectionMode === 'true_false' ||
        block.explicitTagMode === 'true_false' ||
        Boolean(explicitTrueFalseKey) ||
        tfExtracted!.hasInlineKeys ||
        (tfExtracted!.statements.length >= 4 && !isEssayImperativeSubparts));

    let qType: QuestionType = 'single_choice';
    let questionStem = textForOptions;
    let rawOptions: string[] = [];
    let trueFalseStatements: TrueFalseStatement[] | undefined;
    let shortAnswerValue: string | undefined;
    let shortAnswerUnit: string | undefined;

    if (
      block.explicitTagMode !== 'essay' &&
      block.sectionMode !== 'essay' &&
      mcqMatches.length >= 2
    ) {
      questionStem = textForOptions.slice(0, mcqMatches[0].matchStart).trim();
      rawOptions = mcqMatches.map((item, i) => {
        const nextStart =
          i + 1 < mcqMatches.length ? mcqMatches[i + 1].matchStart : textForOptions.length;
        let optText = textForOptions.slice(item.contentStart, nextStart).trim();

        const inlineAnsMatch = optText.match(
          /\n?\s*(?:Đáp\s*án(?:\s*đúng)?|ĐA)\s*[:=-]?\s*([A-D])\b([\s\S]*)$/i
        );
        if (inlineAnsMatch) {
          if (explicitCorrectIndex === null) {
            explicitCorrectIndex = inlineAnsMatch[1].toUpperCase().charCodeAt(0) - 65;
            detectedSource = 'explicit_key';
          }
          optText = optText.slice(0, inlineAnsMatch.index).trim();
        }

        const inlineExpMatch = optText.match(
          /\n?\s*(?:Lời\s*giải|Giải\s*thích|Hướng\s*dẫn\s*giải)\s*[:=-]?\s*([\s\S]*)$/i
        );
        if (inlineExpMatch) {
          extractedExplanation = extractedExplanation || inlineExpMatch[1].trim();
          optText = optText.slice(0, inlineExpMatch.index).trim();
        }

        if (item.starred && explicitCorrectIndex === null) {
          explicitCorrectIndex = i;
          detectedSource = 'asterisk';
        }
        if (optText.startsWith('*')) {
          optText = optText.replace(/^\*+\s*/, '');
          if (explicitCorrectIndex === null) {
            explicitCorrectIndex = i;
            detectedSource = 'asterisk';
          }
        }
        return optText;
      });

      while (rawOptions.length > 2 && rawOptions.length < 4) {
        rawOptions.push(`Phương án ${String.fromCharCode(65 + rawOptions.length)}`);
      }

      if (
        rawOptions.length === 2 &&
        rawOptions.some((o) => /^đúng$/i.test(o.trim())) &&
        rawOptions.some((o) => /^sai$/i.test(o.trim()))
      ) {
        qType = 'true_false';
        trueFalseCount++;
      } else if (explicitMultipleIndices && explicitMultipleIndices.length > 1) {
        qType = 'multiple_choice';
        mcqCount++;
      } else {
        qType = 'single_choice';
        mcqCount++;
      }
    } else if (isGenuineTrueFalse && tfExtracted) {
      qType = 'true_false';
      questionStem = tfExtracted.stem;
      trueFalseStatements = tfExtracted.statements;
      rawOptions = tfExtracted.statements.map((st) => `${st.label}) ${st.text}`);
      if (explicitTrueFalseKey || tfExtracted.hasInlineKeys) {
        detectedSource = explicitTrueFalseKey ? 'explicit_key' : 'asterisk';
      } else if (tfExtracted.statements.every((st) => st.isTrue !== null)) {
        detectedSource = 'knowledge_inference';
      }
      trueFalseCount++;
    } else if (
      block.explicitTagMode === 'short_answer' ||
      block.sectionMode === 'short_answer' ||
      Boolean(explicitShortAnswer)
    ) {
      qType = 'short_answer';
      rawOptions = [];
      shortAnswerValue = explicitShortAnswer?.value;
      shortAnswerUnit = explicitShortAnswer?.unit;
      shortAnswerCount++;
    } else {
      qType = 'essay';
      rawOptions = [];
      detectedSource = 'essay_rubric';
      essayCount++;
    }

    // Apply chemical formula, subscript, superscript, reaction equation & optional IUPAC normalization
    const qNorm = normalizer(questionStem);
    const questionNormalized = qNorm.text;
    let anyChanged = qNorm.changed;
    const normalizedOptions = rawOptions.map((opt) => {
      const oNorm = normalizer(opt);
      if (oNorm.changed) anyChanged = true;
      return oNorm.text;
    });
    if (extractedExplanation) {
      const eNorm = normalizer(extractedExplanation);
      if (eNorm.changed) anyChanged = true;
      extractedExplanation = eNorm.text;
    }
    if (extractedHint) {
      extractedHint = normalizer(extractedHint).text;
    }
    if (anyChanged) {
      iupacNormalizedCount++;
    }

    let finalCorrectIndex = 0;
    if (qType === 'single_choice' || qType === 'multiple_choice' || (qType === 'true_false' && !trueFalseStatements)) {
      let resolved = explicitCorrectIndex;
      if (resolved === null && globalTables.mcqMap.has(block.qNumber)) {
        resolved = globalTables.mcqMap.get(block.qNumber)!;
        detectedSource = 'answer_table';
      }
      if (resolved === null && htmlFormattedMap.has(block.qNumber)) {
        resolved = htmlFormattedMap.get(block.qNumber)!;
        detectedSource = 'formatting';
      }
      if (resolved === null) {
        const inferred = inferCorrectOptionFromKnowledge(questionNormalized, normalizedOptions);
        if (inferred !== null) {
          resolved = inferred;
          detectedSource = 'knowledge_inference';
        } else {
          resolved = -1;
          detectedSource = 'default_first';
        }
      }
      if (resolved < 0 || resolved >= normalizedOptions.length) {
        resolved = -1;
        detectedSource = 'default_first';
      }
      finalCorrectIndex = resolved;
    }

    const meta = detectDomainAndGrade(
      `${questionNormalized} ${normalizedOptions.join(' ')}`,
      defaultDomain,
      defaultGrade
    );

    const hadExplanation = Boolean(extractedExplanation.trim());
    const solution = generateScientificSolution({
      question: questionNormalized,
      options: normalizedOptions,
      correctAnswer: finalCorrectIndex,
      questionType: qType,
      domain: meta.domain,
      grade: meta.grade,
      existingExplanation: extractedExplanation,
      trueFalseStatements,
      shortAnswer: shortAnswerValue,
      shortAnswerUnit,
    });

    // If short_answer had no explicit answer key in the Word file, populate from solver's inferredNumeric if available
    if (qType === 'short_answer' && !shortAnswerValue && solution.inferredNumeric) {
      shortAnswerValue = solution.inferredNumeric.formatted;
      shortAnswerUnit = shortAnswerUnit || solution.inferredNumeric.unit;
      detectedSource = 'knowledge_inference';
    }

    const blockHasOle = detectLegacyOleEquations(block.rawSourceText).hasOleEquation;
    const itemWarnings = [
      ...solution.warnings,
      ...(blockHasOle
        ? ['Chứa đối tượng công thức cũ (MathType/OLE). Cần kiểm tra hiển thị công thức.']
        : []),
    ];

    const solutionSteps = solution.steps;
    const detailedExplanation = solution.explanation;
    if (!hadExplanation) autoExplainedCount++;
    itemWarnings.forEach((warning) => warnings.push(`Câu ${block.qNumber}: ${warning}`));

    const hasMismatch = Boolean(
      itemWarnings.some((w) => /PHÁT HIỆN ĐÁP ÁN KHÔNG KHỚP|mâu thuẫn/i.test(w))
    );

    const parsedItem: ParsedWordQuestion = {
      id: qId,
      lessonId: defaultLessonId,
      grade: meta.grade,
      domain: meta.domain,
      question: questionNormalized,
      questionType: qType,
      options: normalizedOptions,
      correctAnswer: finalCorrectIndex,
      correctAnswers: explicitMultipleIndices || undefined,
      trueFalseStatements,
      shortAnswer: shortAnswerValue,
      shortAnswerUnit,
      shortAnswerTolerance: qType === 'short_answer' ? 0.02 : undefined,
      explanation: detailedExplanation,
      solutionSteps,
      sampleAnswer:
        qType === 'essay' ? extractedExplanation || solutionSteps.join('\n') : undefined,
      rubric:
        qType === 'essay'
          ? extractedRubric ||
            'Nêu đúng công thức/phương trình: 40% điểm; Thay số và đổi đơn vị đúng: 40% điểm; Kết luận chính xác kèm đơn vị: 20% điểm.'
          : undefined,
      allowImageUpload: qType === 'essay' ? true : undefined,
      imageUrl: questionImages[0],
      questionImages: questionImages.length > 0 ? questionImages : undefined,
      questionTables: questionTables.length > 0 ? questionTables : undefined,
      rawSourceBlock: block.rawSourceText,
      approvalStatus: hadExplanation && !hasMismatch && !blockHasOle ? 'approved' : 'pending_review',
      sourceDocument: sourceDocumentName || 'Tài liệu Word (.docx)',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      difficulty: qType === 'essay' ? 'Vận dụng' : meta.difficulty,
      hint:
        extractedHint ||
        (qType === 'essay'
          ? `Câu hỏi tự luận KHTN Lớp ${meta.grade}: Em hãy trình bày công thức, thay số kèm đơn vị chuẩn hoặc chụp ảnh bài giải viết tay tải lên hệ thống.`
          : qType === 'true_false'
          ? `Câu trắc nghiệm Đúng/Sai GDPT 2018: Em hãy chọn Đúng hoặc Sai cho cả 4 phát biểu a, b, c, d.`
          : qType === 'short_answer'
          ? `Câu trả lời ngắn KHTN Lớp ${meta.grade}: Em hãy điền kết quả số (có thể dùng dấu phẩy hoặc dấu chấm thập phân)${shortAnswerUnit ? ` theo đơn vị ${shortAnswerUnit}` : ''}.`
          : `Vận dụng kiến thức trọng tâm KHTN Lớp ${meta.grade} (${
              meta.domain === 'vat-li'
                ? 'Vật lí'
                : meta.domain === 'sinh-hoc'
                ? 'Sinh học'
                : 'Hóa học IUPAC'
            }).`),
      points:
        qType === 'essay'
          ? 2.5
          : qType === 'true_false'
          ? 1.0
          : qType === 'short_answer'
          ? 0.5
          : 0.25,
      autoGeneratedExplanation: !hadExplanation,
      solutionStatus: blockHasOle ? 'needs_review' : solution.status,
      solutionWarnings: itemWarnings,
      hasAnswerMismatch: hasMismatch,
      hasOleEquationWarning: blockHasOle,
      inferredAnswerIndex: solution.inferredAnswer,
      detectedAnswerSource: detectedSource,
    };

    parsedItem.validationStatus = computeQuestionValidationStatus(parsedItem);
    parsedQuestions.push(parsedItem);
  });

  return {
    questions: parsedQuestions,
    warnings,
    stats: {
      totalParsed: parsedQuestions.length,
      autoExplainedCount,
      iupacNormalizedCount,
      essayCount,
      trueFalseCount,
      shortAnswerCount,
      mcqCount,
    },
  };
}

